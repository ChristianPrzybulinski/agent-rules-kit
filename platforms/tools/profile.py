#!/usr/bin/env python3
"""The project profile resolver (KIT-087 P1): one resolved view of a project's kit parameters.

Usage: profile.py resolve [--section S] [--json] [--file F] [ROOT]
       profile.py migrate [ROOT]

A project keeps its kit parameters in `.ai-kit.yaml` at its git top level, validated by
platforms/ci/schemas/profile.schema.json: every key has a default and one reader phase (`x-read-by`), an unknown key
fails, and an `x-<name>` key at the top level or directly in a section is the project's own and is ignored. Only the
kit's skills, hooks, sync-project.sh and the spec-tools action call this tool; a project never does.

Dual read (until KIT-087 P4): a key absent from `.ai-kit.yaml` falls back to its legacy home, with one
`profile: <key> from legacy <path>` line on stderr per key:
- `sdd`: the `sdd:` block of docs/spec/spec.md (checked against spec.schema.json, as check_spec.py did);
- `stacks`: the profile list in the root CLAUDE.md sync marker (`docs,godot:client` -> {'.': docs, client: godot});
- `gates`: the kit-read keys of the gates JSON that `sdd.row_checks.gates` names (`backlog_repo` -> `issue_repo`,
  and of each `repos` entry only `require_fragment`); its other keys are not the kit's.
A key set in both homes must resolve to the same value, else the run fails naming both. A missing `.ai-kit.yaml`
prints one warning line and resolves every key from its legacy home or default. `kit: ">=X.Y"` fails on an older kit.

resolve prints the resolved view (`--section` one section) as YAML in the subset check_spec.py's fallback parser
reads, or as JSON with `--json`; ROOT defaults to the current folder, and its git top level is used. `--file` names
the profile file relative to ROOT (default `.ai-kit.yaml`). migrate writes `.ai-kit.yaml` from the resolved view,
every key that differs from its default, and never overwrites an existing file.

Exit 0 on success, 1 on an invalid profile, a conflict or a refused write, 2 on a usage error. Standard library only
and Python 3.9 compatible: hooks and sync-project.sh run the system python3. The YAML parser and the schema checks
are check_spec.py's (pyyaml when it is installed with jsonschema, else its fallback parser), loaded from beside it.
"""
from __future__ import annotations

import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parents[2]
VALIDATIONS = KIT / "platforms" / "ci" / "validations"
SCHEMAS = KIT / "platforms" / "ci" / "schemas"
FILE = ".ai-kit.yaml"
SPEC_DIR = Path("docs") / "spec"
MARKER = re.compile(r"^<!-- generated by agent-rules-kit sync-project\.sh v[^;]*; profile ([^; ]*); "
                    r"AGENTS\.md is the source -->$")
GATES_KEYS = (("owner", "owner"), ("backlog_repo", "issue_repo"), ("repos", "repos"),
              ("protected_paths", "protected_paths"), ("proof_allowlist", "proof_allowlist"),
              ("generated_neighbours", "generated_neighbours"), ("expected_red_checks", "expected_red_checks"))
PLAIN_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*$")
USAGE = "usage: profile.py resolve [--section S] [--json] [--file F] [ROOT] | profile.py migrate [ROOT]"


def check_spec():
    """check_spec.py as a module: the copy already loaded (check_spec.py --params registers itself), else the file
    beside the validators."""
    module = sys.modules.get("check_spec")
    if module is None:
        spec = importlib.util.spec_from_file_location("check_spec", VALIDATIONS / "check_spec.py")
        module = importlib.util.module_from_spec(spec)
        sys.modules["check_spec"] = module
        spec.loader.exec_module(module)
    return module


def private(key) -> bool:
    return isinstance(key, str) and key.startswith("x-")


def default_of(rule):
    if "default" in rule:
        return json.loads(json.dumps(rule["default"]))
    if "properties" in rule:
        return {key: default_of(prop) for key, prop in rule["properties"].items()}
    return None


def fill(rule, value):
    """A key's value with the defaults of an object's absent sub-keys filled one level deep, as check_spec.py's sdd
    block always was."""
    default = default_of(rule)
    if "properties" in rule and isinstance(value, dict) and isinstance(default, dict):
        return {**default, **{k: v for k, v in value.items() if not private(k)}}
    return value


def resolve_map(rule, given, journeys_dir=None):
    """A section resolved: every schema key at its given value or default, then the free keys (a map section's
    entries) as given; x- keys dropped."""
    out = {}
    for key, prop in rule.get("properties", {}).items():
        value = fill(prop, given[key]) if key in given else default_of(prop)
        if key == "journeys" and value is None:
            value = journeys_dir is not None and journeys_dir.is_dir()
        out[key] = value
    for key, value in given.items():
        if key not in out and not private(key):
            out[key] = value
    return out


def canonical(section, value):
    if section == "stacks":
        value = sorted(value) if isinstance(value, list) else [value]
    return json.dumps(value, sort_keys=True)


def shown(path, root):
    if root is not None:
        try:
            return Path(path).resolve().relative_to(root.resolve()).as_posix()
        except ValueError:
            pass
    return str(path)


class Resolver:
    """One resolution: the values, the stderr notes and the errors. check_value's failures land in check_spec.py's
    failure list, which `checked` moves into this resolver's errors."""

    def __init__(self, root, spec_dir=None, schemas_dir=None, profile_file=FILE):
        self.cs = check_spec()
        self.root = root
        self.spec_dir = spec_dir if spec_dir is not None else (root / SPEC_DIR if root is not None else None)
        self.schemas = schemas_dir if schemas_dir is not None else SCHEMAS
        self.schema = json.loads((self.schemas / "profile.schema.json").read_text(encoding="utf-8"))
        self.profile_file = profile_file
        self.notes, self.errors = [], []
        self.new, self.new_path = {}, None
        self.legacy_sdd = None

    def checked(self, fn, *args):
        start = len(self.cs.failures)
        result = fn(*args)
        self.errors.extend(msg for _, _, msg, *_ in self.cs.failures[start:])
        del self.cs.failures[start:]
        return result

    # --- the new file
    def read_new(self):
        if self.root is None:
            return
        path = self.root / self.profile_file
        self.new_path = shown(path, self.root)
        if not path.is_file():
            self.notes.append(f"profile: warning: no {self.new_path} at {self.root}; every key comes from its legacy "
                              f"home or its default")
            return
        try:
            data = self.cs.load_yaml(path.read_text(encoding="utf-8"))
        except ValueError as e:
            self.errors.append(f"{self.new_path}: invalid YAML ({e})")
            return
        if data is None:
            data = {}
        if not isinstance(data, dict):
            self.errors.append(f"{self.new_path}: the profile must be a map of sections, not {type(data).__name__}")
            return
        props = self.schema["properties"]
        for key, value in data.items():
            key = str(key)
            if private(key):
                continue
            if key not in props:
                self.errors.append(f"{self.new_path}: {key} is not a known key; known: {sorted(props)}")
                continue
            if self.checked(self.cs.check_value, self.new_path, key, value, props[key]):
                self.new[key] = {k: v for k, v in value.items() if not private(k)} if isinstance(value, dict) else value
        self.check_pin()

    def check_pin(self):
        pin = self.new.get("kit")
        if not pin:
            return
        need = tuple(int(n) for n in pin[2:].split("."))
        try:
            have = tuple(int(n) for n in (KIT / "VERSION").read_text(encoding="utf-8").strip().split("-")[0].split("."))
        except (OSError, ValueError):
            return
        if have[:len(need)] < need:
            self.errors.append(f"{self.new_path}: kit {pin} is required, this kit is "
                               f"{'.'.join(str(n) for n in have)}; update the kit (refresh.sh)")

    # --- the legacy homes
    def legacy(self, section):
        """(values, path) of a section's legacy home; ({}, None) when it has none or none is set."""
        if section == "sdd":
            return self.legacy_sdd_block()
        if section == "stacks":
            return self.legacy_stacks()
        if section == "gates":
            return self.legacy_gates()
        return {}, None

    def legacy_sdd_block(self):
        if self.legacy_sdd is not None:
            return self.legacy_sdd
        self.legacy_sdd = ({}, None)
        if self.spec_dir is None:
            return self.legacy_sdd
        index = self.spec_dir / "spec.md"
        if not index.exists():
            return self.legacy_sdd
        data = self.checked(self.cs.frontmatter, index)
        if not isinstance(data, dict):
            return self.legacy_sdd
        rule = json.loads((self.schemas / "spec.schema.json").read_text(encoding="utf-8"))["properties"]["sdd"]
        if "sdd" in data and self.checked(self.cs.check_value, index, "sdd", data["sdd"], rule):
            self.legacy_sdd = (dict(data["sdd"]), shown(index, self.root))
        return self.legacy_sdd

    def legacy_stacks(self):
        if self.root is None or not (self.root / "CLAUDE.md").is_file():
            return {}, None
        lines = (self.root / "CLAUDE.md").read_text(encoding="utf-8").splitlines()
        m = MARKER.match(lines[0]) if lines else None
        if not m or not m.group(1):
            return {}, None
        stacks = {}
        for entry in m.group(1).split(","):
            name, _, folder = entry.partition(":")
            folder = folder.rstrip("/") or "."
            stacks.setdefault(folder, []).append(name)
        values = {folder: names[0] if len(names) == 1 else sorted(names) for folder, names in stacks.items()}
        path = "CLAUDE.md"
        if self.checked(self.cs.check_value, path, "stacks", values, self.schema["properties"]["stacks"]):
            return values, path
        return {}, None

    def legacy_gates(self):
        if self.root is None:
            return {}, None
        sdd = self.resolve_section("sdd", quiet=True)
        rel = (sdd.get("row_checks") or {}).get("gates")
        if not rel:
            return {}, None
        path = self.root / rel
        if not path.is_file():
            self.notes.append(f"profile: warning: sdd.row_checks.gates names {rel}, which does not exist; gates keys "
                              f"keep their defaults")
            return {}, None
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except ValueError as e:
            self.errors.append(f"{rel}: invalid JSON ({e})")
            return {}, None
        if not isinstance(data, dict):
            self.errors.append(f"{rel}: the gates JSON must be an object")
            return {}, None
        values = {}
        for old, new in GATES_KEYS:
            if old in data:
                values[new] = data[old]
        if isinstance(values.get("repos"), dict):
            values["repos"] = {name: ({k: v for k, v in entry.items() if k == "require_fragment"}
                                      if isinstance(entry, dict) else entry)
                               for name, entry in values["repos"].items()}
        if self.checked(self.cs.check_value, rel, "gates", values, self.schema["properties"]["gates"]):
            return values, rel
        return {}, None

    # --- resolution
    def resolve_section(self, section, quiet=False):
        rule = self.schema["properties"][section]
        if section == "kit":
            return self.new.get("kit")
        new = self.new.get(section) or {}
        old, old_path = self.legacy(section)
        given = {}
        for key in list(new) + [k for k in old if k not in new]:
            prop = rule.get("properties", {}).get(key) or rule.get("additionalProperties") or {}
            if key in new and key in old:
                a, b = fill(prop, new[key]), fill(prop, old[key])
                if canonical(section, a) != canonical(section, b) and not quiet:
                    self.errors.append(f"profile: {section}.{key} is {json.dumps(a)} in {self.new_path} and "
                                       f"{json.dumps(b)} in legacy {old_path}; keep one value (the legacy home goes in "
                                       f"KIT-087 P4)")
                given[key] = new[key]
            elif key in new:
                given[key] = new[key]
            else:
                given[key] = old[key]
                if not quiet:
                    self.notes.append(f"profile: {section}.{key} from legacy {old_path}")
        journeys = self.spec_dir / "journeys" if section == "sdd" and self.spec_dir is not None else None
        return resolve_map(rule, given, journeys)

    def resolve(self, sections=None):
        self.read_new()
        names = list(self.schema["properties"]) if sections is None else list(sections)
        return {name: self.resolve_section(name) for name in names}

    def defaults(self, section):
        rule = self.schema["properties"][section]
        if section == "kit":
            return None
        journeys = self.spec_dir / "journeys" if section == "sdd" and self.spec_dir is not None else None
        return resolve_map(rule, {}, journeys)


def resolve(root, sections=None, spec_dir=None, schemas_dir=None, profile_file=FILE):
    """(resolved view, notes, errors) for another kit tool; nothing is printed."""
    resolver = Resolver(root, spec_dir, schemas_dir, profile_file)
    resolved = resolver.resolve(sections)
    return resolved, resolver.notes, resolver.errors


# --- the YAML subset writer: block maps, flow lists and maps, quoted strings (check_spec.py's parser reads it)
def quote(text):
    if "\n" in text or "\r" in text:
        raise ValueError(f"a string with a line break cannot be written: {text!r}")
    if "'" not in text:
        return f"'{text}'"
    if '"' not in text and "\\" not in text:
        return f'"{text}"'
    raise ValueError(f"a string with both quote kinds cannot be written: {text!r}")


def key_text(key):
    key = str(key)
    words = {"null", "true", "false", "yes", "no", "on", "off", "y", "n"}
    return key if PLAIN_KEY.match(key) and key.lower() not in words else quote(key)


def flow(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return quote(value)
    if isinstance(value, list):
        return "[" + ", ".join(flow(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{key_text(k)}: {flow(v)}" for k, v in value.items()) + "}"
    raise ValueError(f"a value of type {type(value).__name__} cannot be written: {value!r}")


def dump(data, indent=0):
    lines, pad = [], " " * indent
    for key, value in data.items():
        if isinstance(value, dict) and value:
            lines.append(f"{pad}{key_text(key)}:")
            lines.extend(dump(value, indent + 2))
        else:
            lines.append(f"{pad}{key_text(key)}: {flow(value)}")
    return lines


# --- command line
def toplevel(path):
    result = subprocess.run(["git", "-C", str(path), "rev-parse", "--show-toplevel"], capture_output=True, text=True,
                            check=False)
    return Path(result.stdout.strip()) if result.returncode == 0 and result.stdout.strip() else path


def usage():
    print(USAGE, file=sys.stderr)
    raise SystemExit(2)


def parse_args(argv):
    if not argv or argv[0] not in ("resolve", "migrate"):
        usage()
    opts, args, rest = {"command": argv[0], "section": None, "json": False, "file": FILE}, [], list(argv[1:])
    while rest:
        arg = rest.pop(0)
        if arg == "--json" and opts["command"] == "resolve":
            opts["json"] = True
        elif arg in ("--section", "--file") and rest and opts["command"] == "resolve":
            opts[arg[2:]] = rest.pop(0)
        elif arg.startswith("-"):
            usage()
        else:
            args.append(arg)
    if len(args) > 1:
        usage()
    opts["root"] = Path(args[0]) if args else Path.cwd()
    return opts


def report(notes, errors):
    for note in notes:
        print(note, file=sys.stderr)
    for error in errors:
        print(f"FAIL: {error}", file=sys.stderr)


def main(argv=None):
    opts = parse_args(sys.argv[1:] if argv is None else argv)
    if not opts["root"].is_dir():
        print(f"profile: {opts['root']} is not a folder", file=sys.stderr)
        return 2
    root = toplevel(opts["root"])
    resolver = Resolver(root, profile_file=opts["file"])
    if opts["section"] is not None and opts["section"] not in resolver.schema["properties"]:
        print(f"profile: unknown section {opts['section']!r}; known: {sorted(resolver.schema['properties'])}",
              file=sys.stderr)
        return 2
    sections = [opts["section"]] if opts["section"] else None
    resolved = resolver.resolve(sections)
    report(resolver.notes, resolver.errors)
    if resolver.errors:
        return 1
    if opts["command"] == "resolve":
        if opts["json"]:
            value = resolved[opts["section"]] if opts["section"] else resolved
            print(json.dumps(value, indent=2, sort_keys=True))
        else:
            print("\n".join(dump(resolved)))
        return 0
    return migrate(resolver, resolved)


def migrate(resolver, resolved):
    target = resolver.root / FILE
    if target.exists() or target.is_symlink():
        print(f"profile: {target} exists; migrate never overwrites it", file=sys.stderr)
        return 1
    out = {}
    for section, value in resolved.items():
        default = resolver.defaults(section)
        if isinstance(value, dict):
            changed = {k: v for k, v in value.items() if not isinstance(default, dict) or default.get(k) != v
                       or k not in default}
            if changed:
                out[section] = changed
        elif value != default:
            out[section] = value
    header = ["# The project profile (KIT-087): the kit parameters only the kit reads, validated by the kit's",
              "# platforms/ci/schemas/profile.schema.json. Written by profile.py migrate from the legacy homes; a key",
              "# left out takes its default. Project-private keys go under x-<name>:."]
    try:
        body = dump(out)
    except ValueError as e:
        print(f"profile: {e}", file=sys.stderr)
        return 1
    text = "\n".join(header + body) + "\n"
    if (resolver.cs.load_yaml(text) or {}) != out:
        print("profile: the written text would not read back as the resolved view; nothing written", file=sys.stderr)
        return 1
    target.write_text(text, encoding="utf-8")
    print(f"profile: wrote {target} ({len(out)} section{'' if len(out) == 1 else 's'})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
