#!/usr/bin/env python3
"""Plugin INDEX.md generator (KIT-040). Usage: gen_index.py [--check] [--kit DIR]

Each plugin's INDEX.md is generated from the plugin itself: the H1 and `Depends on` line from
`.claude-plugin/plugin.json`, one row per skill from `skills/*/SKILL.md` frontmatter (name,
`description`, invoked by user or by user and model), and one bullet per entry of `AGENTS.md`,
`rules/`, `agents/`, `templates/`, `evals/` and `hooks/`. It reads `plugins/*`, never a fixed
plugin list. Without a flag it rewrites every stale INDEX.md and prints each path; `--check`
writes nothing, lists the stale files and exits 1.

The frontmatter is read with a small parser, not PyYAML, so the output is the same whether or not
PyYAML is installed. Skill descriptions are one line, plain or double-quoted.
"""
import json
import re
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parents[2]
REGENERATE = "python3 platforms/tools/gen_index.py"
HEADER = ("<!-- Generated by platforms/tools/gen_index.py from the plugin's files; do not edit."
          " Regenerate: " + REGENERATE + " -->")
MANIFESTS = ("Manifests: `.devin-plugin/plugin.json` (Devin) · `.claude-plugin/plugin.json` (Claude)"
             " · `plugin.json` (Codex).")
SKIP_NAMES = ("INDEX.md", "README.md")
SKIP_EVAL_DIRS = ("results", "mocks")
# directories listed by entry name; skills have their own table
LISTED_DIRS = ("rules", "agents", "templates", "evals", "hooks")


class GenError(Exception):
    """A plugin file the generator cannot read."""


def frontmatter_block(path):
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != "---":
        raise GenError(f"{path}: no frontmatter")
    for position, line in enumerate(lines[1:], start=1):
        if line == "---":
            return lines[1:position]
    raise GenError(f"{path}: frontmatter is not closed")


def scalar(raw, path, key):
    value = raw.strip()
    if value[:1] in (">", "|"):
        raise GenError(f"{path}: `{key}` must be a one-line value, not a block scalar")
    if len(value) >= 2 and value[0] == '"' and value[-1] == '"':
        try:
            return json.loads(value)
        except ValueError:
            return value[1:-1]
    if len(value) >= 2 and value[0] == "'" and value[-1] == "'":
        return value[1:-1].replace("''", "'")
    return value


def read_fields(path):
    """Returns {key: value} for the top-level keys of the frontmatter; a list becomes a list."""
    fields, key = {}, None
    for line in frontmatter_block(path):
        item = re.match(r"^\s+-\s*(.*)$", line)
        if item and key is not None and isinstance(fields.get(key), list):
            fields[key].append(scalar(item.group(1), path, key))
            continue
        match = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if not match:
            continue
        key, raw = match.group(1), match.group(2)
        if raw.strip() == "":
            fields[key] = []
        elif raw.strip().startswith("[") and raw.strip().endswith("]"):
            fields[key] = [scalar(part, path, key) for part in raw.strip()[1:-1].split(",")
                           if part.strip()]
        else:
            fields[key] = scalar(raw, path, key)
    return fields


def invoked_by(fields):
    triggers = fields.get("triggers")
    user_only = (isinstance(triggers, list) and triggers == ["user"]) \
        or str(fields.get("disable-model-invocation", "")).lower() == "true"
    return "user" if user_only else "user, model"


def cell(text):
    return re.sub(r"\s+", " ", text).strip().replace("|", "\\|")


def entries(directory, subdir):
    root = directory / subdir
    if not root.is_dir():
        return []
    names = []
    for entry in sorted(root.iterdir()):
        if entry.name.startswith(".") or entry.name in SKIP_NAMES:
            continue
        if subdir == "evals" and entry.name in SKIP_EVAL_DIRS:
            continue
        names.append(entry.name)
    return names


def skill_rows(plugin_dir):
    root = plugin_dir / "skills"
    if not root.is_dir():
        return []
    rows = []
    for skill_dir in sorted(root.iterdir()):
        if not skill_dir.is_dir() or skill_dir.name.startswith("."):
            continue
        skill_file = skill_dir / "SKILL.md"
        if not skill_file.exists():
            raise GenError(f"{skill_dir}: no SKILL.md")
        fields = read_fields(skill_file)
        description = fields.get("description")
        if not isinstance(description, str) or not description.strip():
            raise GenError(f"{skill_file}: no `description`")
        rows.append((skill_dir.name, invoked_by(fields), cell(description)))
    return rows


def manifest(plugin_dir):
    path = plugin_dir / ".claude-plugin" / "plugin.json"
    if not path.exists():
        raise GenError(f"{plugin_dir}: no .claude-plugin/plugin.json")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except ValueError as error:
        raise GenError(f"{path}: {error}")


def render(plugin_dir):
    """The INDEX.md text of one plugin directory."""
    data = manifest(plugin_dir)
    out = [HEADER, "", f"# {plugin_dir.name}/ — {data.get('description', plugin_dir.name)}", ""]
    dependencies = data.get("dependencies") or []
    if dependencies:
        out += ["Depends on: " + " · ".join(f"`{name}`" for name in dependencies), ""]
    if (plugin_dir / "AGENTS.md").exists():
        out += ["## Always-on", "", "- `AGENTS.md`", ""]
    rows = skill_rows(plugin_dir)
    if rows:
        out += ["## `skills/`", "", "| Skill | Invoked by | Description |", "|---|---|---|"]
        out += [f"| `{name}` | {who} | {description} |" for name, who, description in rows]
        out.append("")
    for subdir in LISTED_DIRS:
        names = entries(plugin_dir, subdir)
        if names:
            out += [f"## `{subdir}/`", ""] + [f"- `{name}`" for name in names] + [""]
    out += [MANIFESTS, ""]
    return "\n".join(out)


def plugin_dirs(kit):
    root = kit / "plugins"
    if not root.is_dir():
        raise GenError(f"{root}: no plugins/ directory")
    return [path for path in sorted(root.iterdir())
            if path.is_dir() and not path.name.startswith(".")]


def stale(kit):
    """Returns [(index_path, expected_text)] for each INDEX.md that differs from its generated form."""
    result = []
    for plugin_dir in plugin_dirs(kit):
        expected = render(plugin_dir)
        index = plugin_dir / "INDEX.md"
        current = index.read_text(encoding="utf-8") if index.exists() else None
        if current != expected:
            result.append((index, expected))
    return result


def main(argv):
    kit, check = KIT, False
    args = list(argv)
    while args:
        arg = args.pop(0)
        if arg == "--check":
            check = True
        elif arg == "--kit" and args:
            kit = Path(args.pop(0)).resolve()
        else:
            print(__doc__.strip().splitlines()[0], file=sys.stderr)
            return 2
    try:
        changed = stale(kit)
    except GenError as error:
        print(f"gen_index: {error}", file=sys.stderr)
        return 2
    if check:
        for index, _ in changed:
            print(f"gen_index: {index.relative_to(kit)} is stale", file=sys.stderr)
        if changed:
            print(f"gen_index: regenerate with `{REGENERATE}` and commit the result", file=sys.stderr)
            return 1
        print("gen_index: plugin indexes are current")
        return 0
    for index, expected in changed:
        index.write_text(expected, encoding="utf-8")
        print(f"wrote {index.relative_to(kit)}")
    if not changed:
        print("gen_index: plugin indexes are current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
