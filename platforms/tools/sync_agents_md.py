#!/usr/bin/env python3
"""Writes or checks the generated path-rule block in each folder's AGENTS.md (KIT-067). Called by sync-project.sh.

Usage: sync_agents_md.py preflight|write|check <repo> <kit-version> <rules-dir>

<rules-dir> holds the rules sync-project.sh rendered for the project: frontmatter with the project's globs, the
generated marker naming the kit rule, then the body. A rule goes to the AGENTS.md of each folder its globs start in
(the directories before the first wildcard, "." for a glob that starts with one); a folder inside another of the same
rule adds nothing. Runtimes that load no rule by path (Codex and others) read the block there; Claude Code loads the
same rules from .claude/rules/, and the root AGENTS.md also through the CLAUDE.md import. A folder that does not exist
gets no block, and nothing here creates one.

preflight refuses, before the sync's first write, a target AGENTS.md that is a symbolic link and any AGENTS.md whose
block markers are broken. write replaces the block in place, appends it to a hand-written file, creates a missing
AGENTS.md, removes a block no rule needs any more and deletes a file the removal leaves empty. check prints one
"sync: ..." line per difference and exits 1.
"""
import os
import re
import sys
from pathlib import Path

BEGIN = "<!-- agent-rules-kit: path rules begin"
END = "<!-- agent-rules-kit: path rules end -->"
RULE_MARKER = re.compile(r"^<!-- agent-rules-kit: generated from (\S+) ")
WILDCARD = re.compile(r"[*?\[{]")
SKIP_DIRS = {".git", ".claude", ".godot", "node_modules", "target", "build", "dist", ".venv", "venv", "__pycache__"}


def parse_rule(path):
    """Returns (rule name, globs, body) of one rendered rule; paths: wins over globs:."""
    lines = path.read_text(encoding="utf-8").splitlines()
    end = lines.index("---", 1)
    lists, key = {"paths": [], "globs": []}, None
    for line in lines[1:end]:
        if line in ("paths:", "globs:"):
            key = line[:-1]
            continue
        match = re.match(r'^\s+-\s+"(.*)"$', line) if line.startswith(" ") else None
        if key and match:
            lists[key].append(match.group(1))
        elif not line.startswith(" "):
            key = None
    marker = RULE_MARKER.match(lines[end + 1]) if end + 1 < len(lines) else None
    if not marker:
        sys.exit(f"sync: {path.name} carries no generated marker after its frontmatter")
    body = "\n".join(lines[end + 2:]).strip()
    return Path(marker.group(1)).stem, lists["paths"] or lists["globs"], body


def folder_of(glob):
    parts = []
    for part in glob.split("/")[:-1]:
        if WILDCARD.search(part):
            break
        parts.append(part)
    return "/".join(parts) or "."


def inside(folder, other):
    return other == "." or folder.startswith(other + "/")


def expected_blocks(repo, version, rules_dir):
    """Returns {folder: block text} for every existing folder that receives at least one rule."""
    per_folder = {}
    for path in sorted(Path(rules_dir).glob("*.md")):
        name, globs, body = parse_rule(path)
        folders = {folder_of(glob) for glob in globs}
        for folder in sorted(folders):
            if any(other != folder and inside(folder, other) for other in folders):
                continue
            listed = [glob for glob in globs if folder_of(glob) == folder or inside(folder_of(glob), folder)]
            per_folder.setdefault(folder, []).append((name, listed, body))
    blocks = {}
    for folder, rules in sorted(per_folder.items()):
        if not (Path(repo) / folder).is_dir():
            continue
        parts = [f"{BEGIN}; generated by platforms/tools/sync-project.sh from plugins/guardrails/rules/, kit {version};"
                 " do not edit -->",
                 "## Path rules",
                 "",
                 "Generated for agents that load no rule by path; Claude Code loads the same rules from `.claude/rules/`."]
        for name, listed, body in sorted(rules):
            parts += ["", f"### `{name}`: " + ", ".join(f"`{glob}`" for glob in listed), "", body]
        parts += ["", END]
        blocks[folder] = "\n".join(parts)
    return blocks


def rel(folder):
    return "AGENTS.md" if folder == "." else f"{folder}/AGENTS.md"


def block_span(lines):
    """Returns (begin, end) line indexes of the one block, None when there is none, or 'broken'."""
    begins = [i for i, line in enumerate(lines) if line.startswith(BEGIN)]
    ends = [i for i, line in enumerate(lines) if line == END]
    if not begins and not ends:
        return None
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        return "broken"
    return begins[0], ends[0]


def generated_files(repo):
    """Returns {folder: AGENTS.md path} for every AGENTS.md that carries a block marker."""
    found = {}
    for base, dirnames, filenames in os.walk(repo):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        if "AGENTS.md" in filenames:
            path = Path(base) / "AGENTS.md"
            if path.is_file() and not path.is_symlink():
                text = path.read_text(encoding="utf-8")
                if BEGIN in text or END in text:
                    found[Path(os.path.relpath(base, repo)).as_posix()] = path
    return found


def without_block(text):
    lines = text.split("\n")
    begin, end = block_span(lines)
    before, after = "\n".join(lines[:begin]), "\n".join(lines[end + 1:])
    head = before.rstrip("\n") + "\n" if before.strip() else ""
    return head + (after.lstrip("\n") if after.strip() else "")


def with_block(text, block):
    lines = text.split("\n")
    span = block_span(lines)
    if span is None:
        return (text.rstrip("\n") + "\n\n" if text.strip() else "") + block + "\n"
    begin, end = span
    return "\n".join(lines[:begin] + block.split("\n") + lines[end + 1:])


def main():
    if len(sys.argv) != 5 or sys.argv[1] not in ("preflight", "write", "check"):
        sys.exit("usage: sync_agents_md.py preflight|write|check <repo> <kit-version> <rules-dir>")
    mode, repo, version, rules_dir = sys.argv[1], Path(sys.argv[2]), sys.argv[3], sys.argv[4]
    blocks = expected_blocks(repo, version, rules_dir)
    present = generated_files(repo)
    problems = []
    for folder, path in sorted(present.items()):
        if block_span(path.read_text(encoding="utf-8").split("\n")) == "broken":
            problems.append(f"sync: {rel(folder)} path-rule block markers are broken (one begin line, then one end"
                            " line); fix them by hand, then rerun")
    if mode == "check":
        for folder, block in blocks.items():
            path = repo / rel(folder)
            text = path.read_text(encoding="utf-8") if path.is_file() else ""
            span = block_span(text.split("\n"))
            if span is None:
                problems.append(f"sync: {rel(folder)} path-rule block missing")
            elif span != "broken" and "\n".join(text.split("\n")[span[0]:span[1] + 1]) != block:
                problems.append(f"sync: {rel(folder)} path-rule block diverges from the kit")
        for folder in sorted(set(present) - set(blocks)):
            problems.append(f"sync: {rel(folder)} path-rule block is generated but not in profile")
        if problems:
            print("\n".join(problems))
        return 1 if problems else 0
    for folder in blocks:
        if (repo / rel(folder)).is_symlink():
            problems.append(f"sync: {rel(folder)} is a symbolic link; the sync writes no path-rule block through it")
    if problems:
        print("\n".join(problems))
        return 1
    if mode == "preflight":
        return 0
    written = removed = 0
    for folder, block in blocks.items():
        path = repo / rel(folder)
        text = path.read_text(encoding="utf-8") if path.is_file() else ""
        new = with_block(text, block)
        if new != text:
            path.write_text(new, encoding="utf-8")
            written += 1
    for folder in sorted(set(present) - set(blocks)):
        path = present[folder]
        new = without_block(path.read_text(encoding="utf-8"))
        if new:
            path.write_text(new, encoding="utf-8")
        else:
            path.unlink()
        removed += 1
    print(f"sync: AGENTS.md path-rule blocks [{written} written, {removed} removed]")
    return 0


if __name__ == "__main__":
    sys.exit(main())
