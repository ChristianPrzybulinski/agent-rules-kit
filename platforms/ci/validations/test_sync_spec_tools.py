"""sync-project.sh and the spec tools after KIT-081 stage 1: the project carries no copy of them. The sync removes the
.github/spec-lint/ copy an older sync generated (its README marker, kit-named files only; any other file stays),
writes spec-lint.yml with the spec-tools action pinned to the kit commit when no workflow runs the spec tools, and
--check fails on a generated copy left and on a workflow line naming .github/spec-lint/."""
import os
import re
import subprocess
import tempfile
import unittest
from pathlib import Path

LAYER = "integration"  # KIT-077 layer (platforms/tools/run_tests.py): starts processes (scripts, git, temp repos)
COVERS = ("platforms/tools/sync-project.sh", "platforms/tools/sync_spec_tools.py",
          "platforms/kits/github/workflows/spec-lint.yml", "platforms/ci/actions/spec-tools/**")

KIT = Path(__file__).resolve().parents[3]
SCRIPT = KIT / "platforms" / "tools" / "sync-project.sh"
TEMPLATE = KIT / "platforms" / "kits" / "github" / "workflows" / "spec-lint.yml"
VERSION = (KIT / "VERSION").read_text(encoding="utf-8").strip()
ACTION = "ChristianPrzybulinski/agent-rules-kit/platforms/ci/actions/spec-tools"
HEADING = "# spec-lint/ — generated copy"
KIT_FILES = ["KIT_VERSION", "check_spec.py", "row_checks.py", "pr_gates.py", "spec_trace.py",
             "check_docs_structure.py", "schemas/spec.schema.json", "schemas/feature.schema.json",
             "schemas/journey.schema.json", "__pycache__/check_spec.cpython-312.pyc"]
CALLER = """name: docs
on: workflow_dispatch
permissions: {}
jobs:
  checks:
    runs-on: ubuntu-latest
    steps:
      # the copy in .github/spec-lint/ is generated
      - run: CI=1 python3 .github/spec-lint/check_spec.py docs/spec .github/spec-lint/schemas
"""


def kit_head():
    return subprocess.run(["git", "-C", str(KIT), "rev-parse", "HEAD"], capture_output=True, text=True,
                          check=True).stdout.strip()


class SpecTools(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.repo = Path(tmp.name) / "repo"
        (self.repo / "docs" / "spec").mkdir(parents=True)
        (self.repo / "AGENTS.md").write_text("# x\n", encoding="utf-8")

    def sync(self, *args, repo=None):
        env = dict(os.environ, GIT_CONFIG_GLOBAL=os.devnull)
        return subprocess.run(["bash", str(SCRIPT), *args, str(repo or self.repo)], capture_output=True, text=True,
                              errors="replace", check=False, env=env)

    def ok(self, *args):
        result = self.sync(*args)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return result

    def write(self, rel, text="x\n"):
        path = self.repo / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def generated_copy(self, *extra):
        self.write(".github/spec-lint/README.md", HEADING + "\n\nGenerated by `platforms/tools/sync-project.sh`.\n")
        for rel in KIT_FILES + list(extra):
            self.write(".github/spec-lint/" + rel)

    def files(self, rel):
        root = self.repo / rel
        return sorted(p.relative_to(root).as_posix() for p in root.rglob("*") if not p.is_dir()) if root.exists() else []

    def test_the_migration_removes_a_generated_copy_and_keeps_unmarked_files(self):
        self.generated_copy("pr-gates.json", "schemas/local.schema.json")
        result = self.ok()
        self.assertEqual(self.files(".github/spec-lint"), ["pr-gates.json", "schemas/local.schema.json"])
        self.assertIn("sync: removed the generated .github/spec-lint/ (11 kit files)", result.stdout)
        self.assertIn("sync: kept .github/spec-lint/pr-gates.json: not a kit file", result.stdout)
        self.assertIn("sync: kept .github/spec-lint/schemas/local.schema.json: not a kit file", result.stdout)
        self.ok("--check")  # what is left is the project's
        for rel in ("pr-gates.json", "schemas/local.schema.json"):
            (self.repo / ".github/spec-lint" / rel).unlink()
        self.generated_copy()
        self.ok()
        self.assertFalse((self.repo / ".github" / "spec-lint").exists())  # nothing kept, the folder goes too

    def test_an_unmarked_folder_and_symbolic_links_are_never_touched(self):
        self.write(".github/spec-lint/check_spec.py", "# the project's own\n")  # no generated README
        self.ok()
        self.assertEqual(self.files(".github/spec-lint"), ["check_spec.py"])
        outside = Path(self.repo.parent, "outside")
        outside.mkdir()
        (outside / "spec_trace.py").write_text("keep\n", encoding="utf-8")
        (self.repo / ".github/spec-lint/check_spec.py").unlink()
        self.generated_copy()
        (self.repo / ".github/spec-lint/row_checks.py").unlink()
        (self.repo / ".github/spec-lint/row_checks.py").symlink_to(outside / "spec_trace.py")
        result = self.ok()
        self.assertIn("sync: kept .github/spec-lint/row_checks.py: not a kit file", result.stdout)
        self.assertTrue((self.repo / ".github/spec-lint/row_checks.py").is_symlink())
        self.assertEqual((outside / "spec_trace.py").read_text(encoding="utf-8"), "keep\n")

    def test_check_fails_on_a_leftover_generated_copy(self):
        self.ok()
        self.generated_copy()
        result = self.sync("--check")
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("sync: .github/spec-lint/ is the generated copy KIT-081 stage 1 retired; rerun sync-project.sh",
                      result.stdout)

    def test_check_names_each_workflow_line_that_runs_the_old_copy(self):
        self.ok()
        self.write(".github/workflows/docs.yml", CALLER)
        result = self.sync("--check")
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        lines = [line for line in result.stdout.splitlines() if "names .github/spec-lint/" in line]
        self.assertEqual(lines, ["sync: .github/workflows/docs.yml:9 names .github/spec-lint/, which the kit no longer"
                                 " writes; run the spec tools through the spec-tools action pinned by SHA"
                                 " (platforms/kits/github/README.md)"])  # line 8 is a comment
        install = self.ok()
        self.assertIn("sync: warning: .github/workflows/docs.yml:9 names .github/spec-lint/", install.stderr)

    def test_the_written_workflow_pins_the_kit_commit_with_its_version(self):
        result = self.ok()
        written = (self.repo / ".github" / "workflows" / "spec-lint.yml").read_text(encoding="utf-8")
        pin = f"uses: {ACTION}@{kit_head()}  # v{VERSION}"
        self.assertIn(pin, written)
        self.assertEqual(written.count(f"uses: {ACTION}@"), 1)
        template = TEMPLATE.read_text(encoding="utf-8")
        self.assertEqual(re.sub(rf"uses: {re.escape(ACTION)}@\S+  # v\S+", pin, template), written)
        self.assertIn(f"sync: wrote .github/workflows/spec-lint.yml: the spec-tools action pinned to {kit_head()}",
                      result.stdout)
        self.assertNotIn(".github/spec-lint", written)
        self.ok("--check")
        again = self.ok()
        self.assertIn("already runs the spec tools in CI; kit workflow not written", again.stdout)
        self.assertEqual((self.repo / ".github/workflows/spec-lint.yml").read_text(encoding="utf-8"), written)

    def test_a_workflow_that_runs_the_spec_tools_another_way_is_kept(self):
        for text in (f"      - uses: {ACTION}@{'0' * 40}  # v1.0.0\n",
                     '      - run: python3 "$AI_KIT_DIR/platforms/ci/validations/check_spec.py" docs/spec x\n'):
            with self.subTest(text=text.strip()[:40]):
                self.write(".github/workflows/docs.yml", "jobs:\n  a:\n    steps:\n" + text)
                self.ok()
                self.assertFalse((self.repo / ".github/workflows/spec-lint.yml").exists())
                self.ok("--check", "--workflow", "docs.yml")
        self.write(".github/workflows/docs.yml", "jobs:\n  a:\n    steps:\n      # uses: " + ACTION + "@x\n")
        result = self.sync("--check", "--workflow", "docs.yml")
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("sync: docs.yml does not run the spec tools", result.stdout)  # a comment runs nothing

    def test_an_existing_workflow_is_never_overwritten(self):
        self.write(".github/workflows/spec-lint.yml", CALLER)
        result = self.sync()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("sync: .github/workflows/spec-lint.yml exists and does not run the spec tools; not overwriting;"
                      " replace its .github/spec-lint/ steps with the spec-tools action, or delete it and rerun the"
                      " sync", result.stderr)
        self.assertEqual((self.repo / ".github/workflows/spec-lint.yml").read_text(encoding="utf-8"), CALLER)
        named = self.sync("--workflow", "docs.yml")  # --workflow names the file the template goes to
        self.assertEqual(named.returncode, 0, named.stdout + named.stderr)
        self.assertIn(f"uses: {ACTION}@{kit_head()}",
                      (self.repo / ".github/workflows/docs.yml").read_text(encoding="utf-8"))
        self.assertEqual((self.repo / ".github/workflows/spec-lint.yml").read_text(encoding="utf-8"), CALLER)

    def test_a_repo_without_docs_spec_gets_no_workflow_but_loses_the_copy(self):
        repo = self.repo.parent / "nospec"
        (repo / ".github/spec-lint").mkdir(parents=True)
        (repo / "AGENTS.md").write_text("# x\n", encoding="utf-8")
        (repo / "pom.xml").write_text("<project/>\n", encoding="utf-8")
        (repo / ".github/spec-lint/README.md").write_text(HEADING + "\n", encoding="utf-8")
        result = self.sync(repo=repo)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("sync: no docs/spec, spec tools skipped", result.stdout)
        self.assertFalse((repo / ".github" / "spec-lint").exists())
        self.assertFalse((repo / ".github" / "workflows").exists())
        check = self.sync("--check", repo=repo)
        self.assertEqual(check.returncode, 0, check.stdout + check.stderr)


if __name__ == "__main__":
    unittest.main()
