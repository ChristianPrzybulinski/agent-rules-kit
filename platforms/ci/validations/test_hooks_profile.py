"""guardrails hooks read the project profile (KIT-087 P2a): plugins/guardrails/hooks/hook_profile.py gives the hooks
`spec_root` and `stacks` from the kit resolver, cached per session under CLAUDE_PLUGIN_DATA and keyed by the profile
files' modification times; the post-edit lint hook checks the spec under `spec_root` and lints `.gd` files only in a
godot folder; the path-rule hook selects rules by the profile's stacks. A missing or failing resolver leaves each hook
as it was before the profile, and no hook blocks on it.

The unit tests load the helper in-process with a stub resolver (a script that counts its runs and prints a fixed
view); the integration tests run the hooks.json commands through bash, as Claude Code does, one of them with the
kit's real resolver; the performance test measures the cached and uncached paths."""
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import unittest
from pathlib import Path

LAYER = "unit"  # KIT-077 layer (platforms/tools/run_tests.py)

KIT = Path(__file__).resolve().parents[3]
PLUGIN = KIT / "plugins" / "guardrails"
HOOKS = json.loads((PLUGIN / "hooks" / "hooks.json").read_text(encoding="utf-8"))
VERSION = (KIT / "VERSION").read_text(encoding="utf-8").strip()
HELPER = PLUGIN / "hooks" / "hook_profile.py"
STUB = """import json, os, sys
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "runs"), "a") as handle:
    handle.write(sys.argv[-1] + "\\n")
view = os.path.join(os.path.dirname(os.path.abspath(__file__)), "view.json")
if not os.path.exists(view):
    sys.exit(1)
print(open(view).read())
"""
BUDGET_S = 0.5  # the path-rule hook's budget (test_hooks_path_rules.py): it runs after every Read and Bash call


def load_helper():
    spec = importlib.util.spec_from_file_location("hook_profile_under_test", HELPER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def marker(profile):
    return f"<!-- generated by agent-rules-kit sync-project.sh v{VERSION}; profile {profile}; AGENTS.md is the source -->\n"


class Stubbed(unittest.TestCase):
    """A project, a plugin data folder and a stub kit whose resolver prints view.json and counts its runs."""

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        base = Path(tmp.name).resolve()
        self.project, self.data, self.kit = base / "project", base / "data", base / "kit"
        (self.project / ".git").mkdir(parents=True)
        tool = self.kit / "platforms" / "tools" / "profile.py"
        tool.parent.mkdir(parents=True)
        tool.write_text(STUB, encoding="utf-8")
        self.env = {"AI_KIT_DIR": str(self.kit), "CLAUDE_PLUGIN_DATA": str(self.data)}

    def set_view(self, spec_root="docs/spec", stacks=None):
        (self.kit / "platforms" / "tools" / "view.json").write_text(
            json.dumps({"spec_root": spec_root, "stacks": stacks or {}, "ci": {}}), encoding="utf-8")

    def runs(self):
        path = self.kit / "platforms" / "tools" / "runs"
        return len(path.read_text(encoding="utf-8").splitlines()) if path.exists() else 0


class HelperTest(Stubbed):
    def setUp(self):
        super().setUp()
        self.hp = load_helper()

    def test_it_returns_spec_root_and_stacks_and_caches_them_per_session(self):
        self.set_view("specs", {"client": "godot"})
        want = {"spec_root": "specs", "stacks": {"client": "godot"}}
        self.assertEqual(self.hp.view(str(self.project), self.env, "s1"), want)
        self.assertEqual(self.hp.view(str(self.project / "sub"), self.env, "s1"), want, "a subfolder: its git top")
        self.assertEqual(self.runs(), 1, "the second call reads the cache")
        self.assertTrue((self.data / "profile" / "s1.json").is_file())
        self.hp.view(str(self.project), self.env, "s2")
        self.assertEqual(self.runs(), 2, "another session resolves on its own")

    def test_a_changed_profile_file_resolves_again(self):
        self.set_view("specs")
        self.hp.view(str(self.project), self.env, "s1")
        for name in (".ai-kit.yaml", "CLAUDE.md"):
            with self.subTest(name=name):
                before = self.runs()
                (self.project / name).write_text(f"x-{name}: 1\n", encoding="utf-8")
                self.hp.view(str(self.project), self.env, "s1")
                self.assertEqual(self.runs(), before + 1)
                self.hp.view(str(self.project), self.env, "s1")
                self.assertEqual(self.runs(), before + 1)

    def test_a_failing_resolver_gives_none_once_per_change(self):
        self.assertIsNone(self.hp.view(str(self.project), self.env, "s1"))  # no view.json: exit 1
        self.assertIsNone(self.hp.view(str(self.project), self.env, "s1"))
        self.assertEqual(self.runs(), 1)

    def test_no_data_folder_resolves_every_call(self):
        self.set_view()
        env = {"AI_KIT_DIR": str(self.kit)}
        self.assertEqual(self.hp.view(str(self.project), env, "s1")["spec_root"], "docs/spec")
        self.hp.view(str(self.project), env, "s1")
        self.assertEqual(self.runs(), 2)

    def test_a_broken_cache_is_replaced_and_an_unwritable_one_gives_none(self):
        self.set_view("specs")
        (self.data / "profile").mkdir(parents=True)
        (self.data / "profile" / "s1.json").write_text("not json", encoding="utf-8")
        self.assertEqual(self.hp.view(str(self.project), self.env, "s1")["spec_root"], "specs")
        self.assertIn(str(self.project), json.loads((self.data / "profile" / "s1.json").read_text(encoding="utf-8")))
        self.assertIsNone(self.hp.view(str(self.project), dict(self.env, CLAUDE_PLUGIN_DATA="/dev/null/x"), "s1"))
        self.assertIsNone(self.hp.view(str(self.project), self.env, {"not": "a session"}) and None)

    def test_the_resolver_order_is_ai_kit_dir_then_the_plugins_kit(self):
        self.assertEqual(self.hp.resolver(self.env), self.kit / "platforms" / "tools" / "profile.py")
        shutil.rmtree(self.kit)
        self.assertEqual(self.hp.resolver(self.env), KIT / "platforms" / "tools" / "profile.py")

    def test_stacks_of_matches_folders_by_prefix(self):
        found = {"stacks": {".": "docs", "client": "godot", "server": ["java", "python"]}}
        self.assertEqual(self.hp.stacks_of(found, "client/a.gd"), {"docs", "godot"})
        self.assertEqual(self.hp.stacks_of(found, "clients/a.gd"), {"docs"})
        self.assertEqual(self.hp.stacks_of(found, "server/x/A.java"), {"docs", "java", "python"})
        self.assertEqual(self.hp.stacks_of(None, "a.gd"), set())

    def test_the_helper_parses_as_python_3_9(self):
        import ast
        ast.parse(HELPER.read_text(encoding="utf-8"), feature_version=(3, 9))


def lint_command():
    found = [hook for group in HOOKS["hooks"]["PostToolUse"] for hook in group["hooks"]
             if "ai-kit lint:" in hook["command"]]
    assert len(found) == 1, "one post-edit lint hook"
    return found[0]


class LintHookTest(Stubbed):
    """The hooks.json post-edit command through bash, with stub tools first on PATH."""

    LAYER = "integration"
    COVERS = ("plugins/guardrails/hooks/**",)

    def setUp(self):
        super().setUp()
        self.bin = self.project.parent / "bin"
        self.bin.mkdir()
        (self.bin / "python3").symlink_to(sys.executable)
        for tool in ("gdformat", "gdlint"):
            stub = self.bin / tool
            stub.write_text('#!/bin/sh\necho "stub $0 finding"\nexit 1\n', encoding="utf-8")
            stub.chmod(0o755)
        check = self.kit / "platforms" / "ci" / "validations" / "check_spec.py"
        check.parent.mkdir(parents=True)
        check.write_text('import sys\nprint("stub check_spec.py on " + sys.argv[1])\nsys.exit(1)\n', encoding="utf-8")

    def edit(self, rel, **env):
        path = self.project / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.touch()
        hook = lint_command()
        full = {"PATH": f"{self.bin}{os.pathsep}/usr/bin{os.pathsep}/bin", "CLAUDE_PLUGIN_ROOT": str(PLUGIN),
                **self.env, **env}
        payload = json.dumps({"session_id": "s1", "tool_name": "Edit", "tool_input": {"file_path": rel},
                              "cwd": str(self.project)})
        return subprocess.run(["bash", "-c", hook["command"]], input=payload, text=True, capture_output=True,
                              timeout=hook["timeout"], cwd=str(self.project), env=full, check=False)

    def test_the_spec_check_follows_spec_root(self):
        self.set_view("specs")
        result = self.edit("specs/features/FEAT-001.md")
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)
        self.assertIn("stub check_spec.py on specs", result.stderr)
        self.assertEqual(self.edit("docs/spec/features/FEAT-001.md").returncode, 0, "docs/spec is not the spec here")

    def test_gd_files_are_linted_only_in_a_godot_folder(self):
        self.set_view(stacks={".": "docs", "client": "godot"})
        linted = self.edit("client/player.gd")
        self.assertEqual(linted.returncode, 2, linted.stdout + linted.stderr)
        self.assertIn("gdlint reported problems", linted.stderr)
        skipped = self.edit("tools/fixture.gd")
        self.assertEqual((skipped.returncode, skipped.stdout, skipped.stderr), (0, "", ""))

    def test_without_a_view_it_keeps_the_old_defaults_and_never_blocks_on_the_profile(self):
        for env in ({}, {"CLAUDE_PLUGIN_ROOT": ""}, {"CLAUDE_PLUGIN_ROOT": "/nonexistent"}):
            with self.subTest(env=env):
                # no view.json: the stub resolver fails, so docs/spec and every .gd file, as before KIT-087 P2a
                spec = self.edit("docs/spec/features/FEAT-001.md", **env)
                self.assertEqual(spec.returncode, 2, spec.stderr)
                self.assertIn("stub check_spec.py on docs/spec", spec.stderr)
                gd = self.edit("tools/fixture.gd", **env)
                self.assertEqual(gd.returncode, 2, gd.stderr)

    def test_an_empty_stacks_map_lints_every_gd_file(self):
        self.set_view()
        self.assertEqual(self.edit("tools/fixture.gd").returncode, 2)


class PathRulesProfileTest(unittest.TestCase):
    """The path-rule hook selects the rules by the resolved stacks: `.ai-kit.yaml` adds a godot folder the marker does
    not list. Runs the kit's real resolver."""

    LAYER = "integration"
    COVERS = ("plugins/guardrails/hooks/**", "platforms/tools/profile.py")

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        base = Path(tmp.name).resolve()
        self.project, self.data = base / "project", base / "data"
        (self.project / "client").mkdir(parents=True)
        (self.project / "client" / "a.gd").write_text("extends Node\n", encoding="utf-8")
        (self.project / "CLAUDE.md").write_text(marker("docs") + "@AGENTS.md\n", encoding="utf-8")
        self.env = dict(os.environ, CLAUDE_PLUGIN_ROOT=str(PLUGIN), CLAUDE_PLUGIN_DATA=str(self.data),
                        CLAUDE_PROJECT_DIR=str(self.project), AI_KIT_DIR=str(KIT))

    def given(self, session):
        hook = [hook for group in HOOKS["hooks"]["PostToolUse"] for hook in group["hooks"]
                if "/hooks/path_rules.py" in hook["command"]][0]
        payload = json.dumps({"session_id": session, "cwd": str(self.project), "hook_event_name": "PostToolUse",
                              "tool_name": "Read", "tool_input": {"file_path": "client/a.gd"}})
        result = subprocess.run(["bash", "-c", hook["command"]], input=payload, text=True, capture_output=True,
                                timeout=hook["timeout"], cwd=str(self.project), env=self.env, check=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        if not result.stdout.strip():
            return []
        context = json.loads(result.stdout)["hookSpecificOutput"]["additionalContext"]
        return [line.split("`")[1] for line in context.splitlines() if line.startswith("ai-kit path rule `")]

    def test_the_profile_stacks_select_the_rules(self):
        self.assertNotIn("godot", self.given("s1"), "the marker alone lists docs")
        (self.project / ".ai-kit.yaml").write_text("stacks: {'.': docs, client: godot}\n", encoding="utf-8")
        self.assertIn("godot", self.given("s2"))

    def test_a_refused_profile_falls_back_to_the_marker(self):
        (self.project / ".ai-kit.yaml").write_text("stacks: {client: unity}\n", encoding="utf-8")
        self.assertNotIn("godot", self.given("s3"))


class Latency(Stubbed):
    LAYER = "performance"  # KIT-077: a latency budget runs alone (performance.yml)

    def test_the_cached_view_is_within_the_budget(self):
        """Uncached is one resolver process; cached is one small JSON read. Real resolver, the kit's own profile."""
        hp = load_helper()
        env = {"AI_KIT_DIR": str(KIT), "CLAUDE_PLUGIN_DATA": str(self.data)}
        start = time.monotonic()
        self.assertIsNotNone(hp.view(str(KIT), env, "lat"))
        uncached = time.monotonic() - start
        cached = []
        for _ in range(5):
            start = time.monotonic()
            hp.view(str(KIT), env, "lat")
            cached.append(time.monotonic() - start)
        print(f"\nhook_profile.view: uncached {uncached * 1000:.0f} ms, cached best {min(cached) * 1000:.1f} ms",
              file=sys.stderr)
        self.assertLess(min(cached), 0.05)
        self.assertLess(uncached, BUDGET_S * 4)  # once per session and profile change, inside the 5 s hook timeout


