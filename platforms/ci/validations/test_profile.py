class Refusals(Project):
    def test_unknown_keys_fail_at_every_level(self):
        self.write(".ai-kit.yaml", "colour: blue\nci:\n  triger: auto\nsdd:\n  trackr: none\n"
                                   "gates:\n  full_risk_paths: [x]\n")
        errors = "\n".join(self.resolve()[2])
        self.assertIn("colour is not a known key", errors)
        self.assertIn("ci.triger is not a known key", errors)
        self.assertIn("sdd.trackr is not a known key", errors)
        self.assertIn("gates.full_risk_paths is not a known key", errors)

    def test_a_value_outside_its_range_fails(self):
        self.write(".ai-kit.yaml", "ci:\n  trigger: nightly\nquality:\n  java: {coverage: {line: 101}}\n"
                                   "stacks: {client: unity}\n")
        errors = "\n".join(self.resolve()[2])
        self.assertIn("ci.trigger 'nightly' is not one of ['auto', 'dispatch']", errors)
        self.assertIn("quality.java.coverage.line 101 is above the maximum 100", errors)
        self.assertIn("stacks.client 'unity' does not match", errors)

    def test_x_keys_are_accepted_and_ignored(self):
        self.write(".ai-kit.yaml", "x-team: {anything: [1, 2]}\nci:\n  x-note: free text\n  trigger: auto\n"
                                   "stacks: {x-old: whatever, client: godot}\n")
        resolved, _, errors = self.resolve()
        self.assertEqual(errors, [])
        self.assertNotIn("x-team", resolved)
        self.assertEqual(resolved["ci"], {"trigger": "auto", "spec_tools_checks": ["spec"]})
        self.assertEqual(resolved["stacks"], {"client": "godot"})


