class KindPresets(Project):
    """KIT-088: project.kind is a preset of defaults. A key resolves to the project's value in `.ai-kit.yaml`, else
    the kind's preset, else the schema default."""

    def kind(self, kind, extra=""):
        self.write(".ai-kit.yaml", f"project:\n  kind: {kind}\n{extra}")
        resolved, notes, errors = self.resolve()
        self.assertEqual((errors, notes), ([], []))
        return resolved

    def test_business_is_every_schema_default(self):
        business = self.kind("business")
        self.write(".ai-kit.yaml", "x-none: 1\n")
        self.assertEqual(business, {**self.resolve()[0], "project": {"kind": "business"}})

    def test_game_presets_the_game_keys(self):
        resolved = self.kind("game")
        sdd = resolved["sdd"]
        self.assertEqual(sdd["vision_sections"], ["Pillars", "Core loop", "Direction", "References"])
        self.assertEqual(sdd["passes"], ["greybox", "polish"])
        self.assertEqual(sdd["acceptance"], "playtest")
        self.assertEqual(sdd["plan_sections"], ["Design", "Contract", "Data", "UI", "Assets", "Flag", "Tests",
                                                "Observability", "Risks", "Dependencies"])
        self.assertEqual(resolved["evidence"]["visual_approval"], "owner")
        self.assertEqual((sdd["flow"], sdd["task_table"], sdd["needs"]), ("full", True, True), "full flow kept")
        self.assertEqual(resolved["release"], {"versioning": "semver"})

    def test_tooling_presets_the_feat_only_flow(self):
        sdd = self.kind("tooling")["sdd"]
        self.assertEqual({k: sdd[k] for k in ("flow", "needs", "task_table", "record_when", "pr_unit", "plan_sections",
                                               "release")},
                         {"flow": "feat-only", "needs": False, "task_table": False, "record_when": "big-change",
                          "pr_unit": "feat", "plan_sections": ["Tests", "Risks"], "release": "manual"})
        self.assertEqual((sdd["passes"], sdd["acceptance"], sdd["id_prefix"]), ([], "captures", {"feature": "FEAT"}))

    def test_explicit_keys_override_the_preset(self):
        resolved = self.kind("game", "sdd:\n  passes: []\n  plan_sections: [Tests, Risks]\n"
                                     "evidence:\n  visual_approval: reviewer\n")
        self.assertEqual(resolved["sdd"]["passes"], [])
        self.assertEqual(resolved["sdd"]["plan_sections"], ["Tests", "Risks"])
        self.assertEqual(resolved["sdd"]["acceptance"], "playtest", "a key left out still takes the preset")
        self.assertEqual(resolved["evidence"]["visual_approval"], "reviewer")
        resolved = self.kind("tooling", "sdd:\n  flow: full\n  task_table: true\n")
        self.assertEqual((resolved["sdd"]["flow"], resolved["sdd"]["task_table"]), ("full", True))
        self.assertEqual(resolved["sdd"]["record_when"], "big-change")

    def test_an_sdd_block_in_spec_md_does_not_override_the_preset(self):
        self.spec("sdd:\n  needs: true\n")
        self.write(".ai-kit.yaml", "project: {kind: tooling}\n")
        resolved, notes, errors = self.resolve(["sdd"])
        self.assertEqual((errors, notes), ([], []))
        self.assertFalse(resolved["sdd"]["needs"], "KIT-087 P4: the sdd: block of spec.md is not read")
        self.assertEqual(resolved["sdd"]["flow"], "feat-only")

    def test_the_preset_applies_to_a_single_section(self):
        self.write(".ai-kit.yaml", "project: {kind: game}\n")
        self.assertEqual(self.resolve(["sdd"])[0]["sdd"]["acceptance"], "playtest")

