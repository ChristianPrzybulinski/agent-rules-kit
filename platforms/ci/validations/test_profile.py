class SchemaContract(unittest.TestCase):
    LAYER = "contract"  # the kit's own schema and sources, read in-process

    def walk(self, rule, path):
        for key, prop in rule.get("properties", {}).items():
            yield f"{path}.{key}", prop
            yield from self.walk(prop, f"{path}.{key}")
        extra = rule.get("additionalProperties")
        if isinstance(extra, dict):
            yield from self.walk(extra, f"{path}.*")

    def test_every_key_has_a_default_and_one_reader_phase(self):
        self.assertEqual(list(SCHEMA["properties"]), SECTIONS)
        self.assertIs(SCHEMA["additionalProperties"], False)
        for name, prop in self.walk(SCHEMA, ""):
            if ".row_checks." in name and name.count(".") > 3:
                continue  # fields of a row_checks entry (a tests item, an assets map) are values, not keys
            with self.subTest(key=name):
                self.assertIn(prop.get("x-read-by"), PHASES)
                self.assertTrue("default" in prop or "properties" in prop, "no default")
        for section, rule in SCHEMA["properties"].items():
            if rule.get("type") == "object":
                with self.subTest(section=section):
                    self.assertEqual(rule.get("patternProperties", {}).keys(), {"^x-"})

    def test_the_sdd_section_holds_the_23_spec_keys_plus_the_two_cut_keys(self):
        spec = SPEC_SCHEMA["properties"]["sdd"]["properties"]
        sdd = SCHEMA["properties"]["sdd"]["properties"]
        self.assertEqual(len(spec), 23)
        self.assertEqual(set(sdd) - set(spec), {"task_cut", "decision_folding"})
        for key, rule in spec.items():
            if key == "journeys":
                continue  # nullable here: null is "on when docs/spec/journeys exists", the legacy absent key
            with self.subTest(key=key):
                self.assertEqual(self.without_read_by(sdd[key]), rule)

    def without_read_by(self, rule):
        if isinstance(rule, dict):
            return {k: self.without_read_by(v) for k, v in rule.items() if k != "x-read-by"}
        if isinstance(rule, list):
            return [self.without_read_by(v) for v in rule]
        return rule

    def test_ci_trigger_defaults_to_dispatch(self):
        self.assertEqual(SCHEMA["properties"]["ci"]["properties"]["trigger"]["default"], "dispatch")

    def test_the_schema_is_valid_json_schema(self):
        try:
            import jsonschema
        except ImportError:
            if os.environ.get("CI"):
                raise
            self.skipTest("jsonschema missing")
        jsonschema.Draft202012Validator.check_schema(SCHEMA)

    def test_the_resolver_parses_as_python_3_9_and_imports_only_the_standard_library(self):
        for path in (TOOL, CHECK_SPEC):
            with self.subTest(path=path.name):
                tree = ast.parse(path.read_text(encoding="utf-8"), feature_version=(3, 9))
                names = {a.name.split(".")[0] for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names}
                names |= {n.module.split(".")[0] for n in ast.walk(tree)
                          if isinstance(n, ast.ImportFrom) and n.module and n.level == 0}
                stdlib = getattr(sys, "stdlib_module_names", None)  # Python 3.10+; the parse above is the 3.9 check
                if stdlib is not None:
                    self.assertLessEqual(names - {"yaml", "jsonschema"}, set(stdlib))
        self.assertNotIn("import yaml", TOOL.read_text(encoding="utf-8"))  # it parses through check_spec.py


class KitOwnProfile(unittest.TestCase):
    """KIT-087 P1b: the kit carries its own .ai-kit.yaml; check_kit.py fails when it does not resolve (its integration
    test breaks a copy). Here the real file resolves with no note, sets only keys off their defaults, and gives the kit
    CI trigger its workflows have."""
    LAYER = "contract"  # the kit's own profile, read in-process

    def test_the_kits_profile_resolves_cleanly_and_sets_only_keys_off_their_defaults(self):
        resolver = profile.Resolver(KIT)
        resolved = resolver.resolve()
        self.assertEqual((resolver.errors, resolver.notes), ([], []))
        self.assertEqual(resolved["ci"]["trigger"], "auto")
        given = profile.check_spec().load_yaml((KIT / ".ai-kit.yaml").read_text(encoding="utf-8"))
        for section, value in given.items():
            default = resolver.defaults(section)
            for key, sub in (value.items() if isinstance(value, dict) else [(None, value)]):
                with self.subTest(key=f"{section}.{key}"):
                    if isinstance(default, dict) and key in default:
                        self.assertNotEqual(sub, default[key])
                    elif not isinstance(default, dict):
                        self.assertNotEqual(sub, default)


class CommandLine(Project):
    LAYER = "integration"  # starts the resolver and check_spec.py as processes, with and without pyyaml
    COVERS = ("platforms/tools/profile.py", "platforms/ci/validations/check_spec.py",
              "platforms/ci/schemas/profile.schema.json", "platforms/ci/schemas/spec.schema.json")

    def run_tool(self, *args, flags=()):
        env = {k: v for k, v in os.environ.items() if k != "CI"}
        return subprocess.run([sys.executable, "-B", *flags, str(TOOL), *args], capture_output=True, text=True,
                              check=False, env=env, cwd=self.root)

    def test_unknown_keys_fail_with_and_without_pyyaml(self):
        self.write(".ai-kit.yaml", "ci:\n  trigger: dispatch  # on demand\n  triger: auto\n")
        for flags in ((), ("-S",)):  # -S hides site-packages: pyyaml and jsonschema
            with self.subTest(flags=flags):
                result = self.run_tool("resolve", "--json", str(self.root), flags=flags)
                self.assertEqual(result.returncode, 1, result.stderr)
                self.assertIn("ci.triger is not a known key", result.stderr)

    def test_both_parsers_resolve_the_same_view(self):
        self.write(".ai-kit.yaml", "x-team: 1\nstacks:\n  '.': docs\n  client: godot\nsdd:\n  row_check: ~\n"
                                   "  plan_sections:\n    - Tests\n    - Risks\nreview: {rounds: 2}\n")
        views = []
        for flags in ((), ("-S",)):
            result = self.run_tool("resolve", "--json", str(self.root), flags=flags)
            self.assertEqual(result.returncode, 0, result.stderr)
            views.append(json.loads(result.stdout))
        self.assertEqual(views[0], views[1])
        self.assertEqual(views[0]["review"]["rounds"], 2)

    def test_section_and_usage(self):
        result = self.run_tool("resolve", "--section", "ci", "--json", str(self.root))
        self.assertEqual(json.loads(result.stdout), {"spec_tools_checks": ["spec"], "trigger": "dispatch"})
        self.assertEqual(self.run_tool("resolve", "--section", "merge", str(self.root)).returncode, 2)
        usage = self.run_tool("frobnicate")
        self.assertEqual(usage.returncode, 2)
        self.assertIn("usage:", usage.stderr)

    def test_migrate_writes_the_file_once_and_it_resolves_the_same(self):
        self.write("CLAUDE.md", MARKER.format("docs,godot:client"))
        self.spec("sdd:\n  tracker: none\n  protected_paths: {'game/protocol/**': contract}\n")
        before = self.run_tool("resolve", "--json", str(self.root))
        written = self.run_tool("migrate", str(self.root))
        self.assertEqual(written.returncode, 0, written.stderr)
        text = (self.root / ".ai-kit.yaml").read_text(encoding="utf-8")
        self.assertIn("tracker: 'none'", text)
        self.assertNotIn("max_chain", text, "a key at its default is left out")
        for flags in ((), ("-S",)):
            after = self.run_tool("resolve", "--json", str(self.root), flags=flags)
            self.assertEqual(after.returncode, 0, after.stderr)
            self.assertEqual(json.loads(after.stdout), json.loads(before.stdout))
            self.assertNotIn("from legacy", after.stderr)
        again = self.run_tool("migrate", str(self.root))
        self.assertEqual(again.returncode, 1)
        self.assertIn("migrate never overwrites it", again.stderr)
        self.assertEqual((self.root / ".ai-kit.yaml").read_text(encoding="utf-8"), text)

    def test_params_output_is_unchanged_on_the_kits_own_spec_fixtures(self):
        """check_spec.py --params delegates to the resolver and prints what the legacy sdd_params resolved."""
        template = KIT / "plugins" / "guardrails" / "templates" / "spec-index.md"
        self.write("docs/spec/spec.md", template.read_text(encoding="utf-8").replace("YYYY-MM-DD", "2026-11-16"))
        fixtures = [KIT / "platforms" / "ci" / "fixtures" / "consumer" / "docs" / "spec", self.root / "docs" / "spec"]
        cs = profile.check_spec()
        for spec_dir in fixtures:
            with self.subTest(spec=str(spec_dir)):
                index = spec_dir / "spec.md"
                data = cs.frontmatter(index) if index.exists() else {}
                expected = cs.sdd_params(index, data, SPEC_SCHEMA, spec_dir)
                for flags in ((), ("-S",)):
                    env = {k: v for k, v in os.environ.items() if k != "CI"}
                    result = subprocess.run([sys.executable, "-B", *flags, str(CHECK_SPEC), "--params", str(spec_dir),
                                             str(SCHEMAS)], capture_output=True, text=True, check=False, env=env)
                    self.assertEqual(result.returncode, 0, result.stderr)
                    self.assertEqual(result.stdout, json.dumps(expected, indent=2, sort_keys=True) + "\n")

    def test_params_reads_the_new_file_first(self):
        self.spec()
        self.write(".ai-kit.yaml", "sdd:\n  tracker: none\n  task_cut: {bundle_exclude: ['changelog.d/**']}\n")
        result = subprocess.run([sys.executable, "-B", str(CHECK_SPEC), "--params", str(self.root / "docs" / "spec"),
                                 str(SCHEMAS)], capture_output=True, text=True, check=False,
                                env={k: v for k, v in os.environ.items() if k != "CI"})
        self.assertEqual(result.returncode, 0, result.stderr)
        params = json.loads(result.stdout)
        self.assertEqual(params["tracker"], "none")
        self.assertNotIn("task_cut", params, "--params keeps the keys spec.schema.json defines")


