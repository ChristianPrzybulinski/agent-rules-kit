class Project(unittest.TestCase):
    """A throwaway project root (no git: the in-process resolver takes the root as given)."""

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name).resolve()
        (self.root / "docs" / "spec").mkdir(parents=True)

    def write(self, rel, text):
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def spec(self, extra=""):
        self.write("docs/spec/spec.md", SPEC_MD.format(extra=extra))

    def resolve(self, sections=None):
        return profile.resolve(self.root, sections)


class Defaults(Project):
    def test_a_missing_file_gives_every_default_and_one_warning(self):
        resolved, notes, errors = self.resolve()
        self.assertEqual(errors, [])
        self.assertEqual(len(notes), 1)
        self.assertIn("profile: warning: no .ai-kit.yaml", notes[0])
        self.assertEqual(list(resolved), SECTIONS)
        self.assertIsNone(resolved["kit"])
        self.assertEqual(resolved["stacks"], {})
        self.assertEqual(resolved["ci"], {"trigger": "dispatch", "spec_tools_checks": ["spec"]})
        self.assertEqual(resolved["changelog"], {"mode": "file", "fragment_glob": "changelog.d/*.md",
                                                 "consolidate_threshold": 25})
        self.assertEqual(resolved["gates"], {"owner": None, "issue_repo": None, "repos": {}, "protected_paths": {},
                                             "proof_allowlist": [], "generated_neighbours": [],
                                             "expected_red_checks": {}})
        self.assertEqual(resolved["tracker"]["labels"], {"blocked": ["blocked"], "progress": ["status:in-progress"]})
        self.assertEqual(resolved["models"], {"tiers": {"small": "small", "mid": "mid", "top": "top"}})
        self.assertEqual(resolved["sdd"]["task_cut"]["longest_chain_max_complexity"], "High")
        self.assertEqual(resolved["sdd"]["decision_folding"], {"marker": "→ folded into"})
        self.assertFalse(resolved["sdd"]["journeys"])
        (self.root / "docs" / "spec" / "journeys").mkdir()
        self.assertTrue(self.resolve(["sdd"])[0]["sdd"]["journeys"], "journeys stays on when its folder exists")

    def test_values_merge_over_the_defaults(self):
        self.write(".ai-kit.yaml", "ci:\n  trigger: auto\nsdd:\n  bundle: {rows: 3}\n"
                                   "stacks: {'.': docs, client: godot, server: [java, python]}\n")
        resolved, notes, errors = self.resolve()
        self.assertEqual((errors, notes), ([], []))
        self.assertEqual(resolved["ci"]["trigger"], "auto")
        self.assertEqual(resolved["sdd"]["bundle"], {"rows": 3, "points": 3, "high_rows": 1})
        self.assertEqual(resolved["stacks"], {".": "docs", "client": "godot", "server": ["java", "python"]})

    def test_an_older_kit_than_the_pin_fails(self):
        self.write(".ai-kit.yaml", "kit: '>=999'\n")
        errors = self.resolve()[2]
        self.assertEqual(len(errors), 1)
        self.assertIn("kit >=999 is required", errors[0])
        self.write(".ai-kit.yaml", "kit: '>=1.0'\n")
