VERSION = (KIT / "VERSION").read_text(encoding="utf-8").strip()
BUDGET_S = 0.5  # the InstructionsLoaded hook's budget; this one runs after every Read and Bash call


def marker(profile=None):
    """The sync marker; with a profile list, the form kit 16 and earlier wrote (KIT-087 P4: the list is not read)."""
    listed = f" profile {profile};" if profile else ""
    return f"<!-- generated by agent-rules-kit sync-project.sh v{VERSION};{listed} AGENTS.md is the source -->\n"


def stacks(profile):
    """The `.ai-kit.yaml` stacks of a sync profile list: docs,godot:client is {'.': docs, client: godot}."""
    lines = ["stacks:"]
    for entry in profile.split(","):
        name, _, folder = entry.partition(":")
        lines.append(f"  '{folder or '.'}': {name}")
    return "\n".join(lines) + "\n"


def given(output):
    """The rule names a hook output gives, in order."""
    if not output:
        return []
    context = json.loads(output)["hookSpecificOutput"]["additionalContext"]
    return [line.split("`")[1] for line in context.splitlines() if line.startswith(pr.CONTEXT + " `")]


class Project(unittest.TestCase):
    """A throwaway project synced with a profile, and the plugin's data folder."""

    profile = "godot"

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        self.project = self.root / "project"
        self.data = self.root / "data"
        (self.project / "src").mkdir(parents=True)
        (self.project / "src" / "a.gd").write_text("extends Node\n", encoding="utf-8")
        if self.profile:
            (self.project / "CLAUDE.md").write_text(marker() + "@AGENTS.md\n", encoding="utf-8")
            (self.project / ".ai-kit.yaml").write_text(stacks(self.profile), encoding="utf-8")
        self.env = {"CLAUDE_PROJECT_DIR": str(self.project), "CLAUDE_PLUGIN_DATA": str(self.data)}

    def event(self, tool="Read", session="s1", **tool_input):
        return json.dumps({"session_id": session, "cwd": str(self.project), "hook_event_name": "PostToolUse",
                           "tool_name": tool, "tool_input": tool_input or {"file_path": "src/a.gd"}})

    def run_hook(self, *args, **kwargs):
        return pr.run(self.event(*args, **kwargs), self.env)

    def log(self):
        path = self.data / pr.LOG
        return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()] if path.exists() else []


class GlobTest(unittest.TestCase):
    def match(self, glob, path):
        return pr.glob_regex(glob).match(path) is not None

    def test_double_star_slash_may_be_empty_or_many_folders(self):
        for path in ("a.gd", "client/a.gd", "client/ui/deep/a.gd"):
            self.assertTrue(self.match("**/*.gd", path), path)
        self.assertTrue(self.match("**/project.godot", "project.godot"))
        self.assertTrue(self.match("**/assets/**", "assets/x.png"))
        self.assertTrue(self.match("**/assets/**", "game/assets/ui/x.png"))
        self.assertTrue(self.match("docs/spec/**/*.md", "docs/spec/spec.md"))
        self.assertTrue(self.match("docs/spec/**/*.md", "docs/spec/features/FEAT-001.md"))

    def test_star_stays_inside_a_folder_and_the_match_is_anchored(self):
        self.assertFalse(self.match("*.gd", "client/a.gd"))
        self.assertFalse(self.match("**/*.gd", "a.gdx"))
        self.assertFalse(self.match("**/*.gd", "a.gd.bak"))
        self.assertFalse(self.match("docs/spec/**/*.md", "other/docs/spec/a.md"))
        self.assertFalse(self.match("**/assets/**", "myassets/x.png"))
        self.assertTrue(self.match("**/test_*.py", "tools/test_x.py"))
        self.assertTrue(self.match("**/Dockerfile*", "server/Dockerfile.dev"))
        self.assertFalse(self.match("**/a?.gd", "a/x.gd"))

    def test_every_kit_rule_has_paths_and_a_body(self):
        for rule in sorted((PLUGIN / "rules").glob("*.md")):
            globs, body = pr.read_rule(rule)
            self.assertTrue(globs, rule.name)
            self.assertTrue(body.startswith(("Always", "Never", "-")) or body[:1].isupper(), rule.name)
            self.assertNotIn("\n---\n", "\n" + body[:200], f"{rule.name}: frontmatter left in the body")


class BashWordsTest(unittest.TestCase):
    def test_path_words_of_common_reads(self):
        cases = {
            "cat a.gd": ["a.gd"],
            "sed -n '1,20p' ./src/a.gd | head": ["./src/a.gd"],
            "for f in x.gd y.gd; do cat -n $f; done": ["x.gd", "y.gd"],
            "grep -n foo b.gd:12": ["b.gd"],
            "rg -n foo src/b.gd:12:3: && wc -l docs/x.md": ["src/b.gd", "docs/x.md"],
            "python3 tool.py --input=data/in.json": ["tool.py", "data/in.json"],
            'cat "my dir/a.gd" > out.txt': ["my dir/a.gd", "out.txt"],
            "curl -s https://example.com/a.gd; echo . ..": [],
            "ls": [],
        }
        for command, want in cases.items():
            with self.subTest(command=command):
                self.assertEqual(pr.path_words(command), want)

    def test_an_open_quote_falls_back_to_whitespace(self):
        self.assertEqual(pr.path_words("cat 'a.gd b.gd"), ["'a.gd", "b.gd"])

    def test_a_long_command_is_cut(self):
        self.assertEqual(len(pr.command_words("cat " + " ".join(f"f{n}.gd" for n in range(1000)))), pr.MAX_WORDS)


class GateTest(Project):
    def test_a_synced_project_gets_its_rules_once(self):
        self.assertEqual(given(self.run_hook()), ["code", "godot"])
        self.assertEqual(self.run_hook(), "")
        self.assertEqual(self.run_hook(tool="Edit", file_path=str(self.project / "src" / "a.gd")), "")
        self.assertEqual(given(self.run_hook(session="s2")), ["code", "godot"], "a new session gets them again")

    def test_no_marker_no_output(self):
        for text in (None, "# hand-written\n", "@AGENTS.md\n" + marker(),
                     marker().replace("sync-project.sh", "other.sh")):
            with self.subTest(text=text):
                claude = self.project / "CLAUDE.md"
                if text is None:
                    claude.unlink(missing_ok=True)
                else:
                    claude.write_text(text, encoding="utf-8")
                self.assertEqual(self.run_hook(session=f"gate-{text!r}"), "")
        self.assertFalse((self.data / pr.STATE).exists(), "an unsynced project leaves no state")

    def test_the_root_falls_back_to_the_event_cwd(self):
        self.env.pop("CLAUDE_PROJECT_DIR")
        self.assertEqual(given(self.run_hook()), ["code", "godot"])

    def test_without_a_data_folder_nothing_is_given(self):
        self.env.pop("CLAUDE_PLUGIN_DATA")
        self.assertEqual(self.run_hook(), "")

    def test_bash_and_grep_reach_the_rule(self):
        command = "for f in src/a.gd src/b.gd; do cat -n $f; done"
        self.assertEqual(given(self.run_hook(tool="Bash", command=command)), ["code", "godot"])
        self.assertEqual(given(self.run_hook(tool="Grep", session="s2", pattern="extends", path="src/a.gd")),
                         ["code", "godot"])
        self.assertEqual(self.run_hook(tool="Grep", session="s3", pattern="x", path="src"), "", "a folder is no file")

    def test_a_command_from_another_tool_is_not_read(self):
        self.assertEqual(self.run_hook(tool="Write", file_path="notes.txt", command="cat src/a.gd"), "")

    def test_a_path_outside_the_root_matches_as_written(self):
        outside = self.root / "elsewhere" / "b.gd"
        self.assertEqual(given(self.run_hook(file_path=str(outside))), ["code", "godot"])
        [record, _] = self.log()
        self.assertEqual(record["trigger_file_path"], os.path.realpath(outside))

    def test_the_context_names_the_rule_its_globs_trigger_and_kit_files(self):
        context = json.loads(self.run_hook())["hookSpecificOutput"]["additionalContext"]
        globs, body = pr.read_rule(PLUGIN / "rules" / "godot.md")
        self.assertTrue(context.startswith(pr.CONTEXT + " `code`"), context[:80])
        self.assertIn(pr.CONTEXT + " `godot` (plugin guardrails, `rules/godot.md`; paths "
                      + ", ".join(f"`{glob}`" for glob in globs) + "): this tool call touched `src/a.gd`", context)
        self.assertIn(body, context)
        self.assertIn(f"`{pr.PLUGIN}/skills/<skill>/references/<file>`", context)  # review of PR #261 (N4)
        self.assertNotIn("\ntrigger: glob", context, "no frontmatter")
        self.assertEqual(json.loads(self.run_hook(session="s9"))["hookSpecificOutput"]["hookEventName"], "PostToolUse")


