class HookCommandTest(Project):
    """The hooks.json command through bash, with the variables Claude Code sets."""

    LAYER = "integration"
    COVERS = ("plugins/guardrails/hooks/**",)

    def command(self):
        found = [(group, hook) for group in HOOKS["hooks"]["PostToolUse"] for hook in group["hooks"]
                 if "/hooks/path_rules.py" in hook["command"]]
        self.assertEqual(len(found), 1, "one path-rule hook")
        return found[0]

    def run_command(self, payload, **env):
        full = dict(os.environ, CLAUDE_PLUGIN_ROOT=str(PLUGIN), **self.env)
        full.update(env)
        return subprocess.run(["bash", "-c", self.command()[1]["command"]], input=payload, text=True,
                              capture_output=True, timeout=self.command()[1]["timeout"], cwd=str(self.project),
                              env=full, check=False)

    def test_declared_after_every_tool_that_reads_or_edits_a_file(self):
        group, hook = self.command()
        self.assertEqual(group["matcher"], "^(Read|Edit|Write|MultiEdit|NotebookEdit|Bash|Grep)$")
        self.assertEqual(hook["type"], "command")
        self.assertLessEqual(hook["timeout"], 5)

    def test_gives_the_rule_and_exits_0(self):
        result = self.run_command(self.event())
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(given(result.stdout.strip()), ["code", "godot"])

    def test_never_blocks(self):
        for payload, env in (("not json", {}), (self.event(session="x"), {"CLAUDE_PLUGIN_ROOT": "/nonexistent"}),
                             (self.event(session="y"), {"CLAUDE_PLUGIN_ROOT": ""})):
            with self.subTest(payload=payload, env=env):
                result = self.run_command(payload, **env)
                self.assertEqual((result.returncode, result.stdout), (0, ""))

    def test_parallel_calls_give_each_rule_once(self):
        """Claude Code runs the hooks of parallel tool calls at once: one lock covers the state's read and write."""
        full = dict(os.environ, CLAUDE_PLUGIN_ROOT=str(PLUGIN), **self.env)
        hooks = [subprocess.Popen(["bash", "-c", self.command()[1]["command"]], stdin=subprocess.PIPE,
                                  stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, cwd=str(self.project),
                                  env=full) for _ in range(8)]
        time.sleep(1)  # every hook is up and blocked reading stdin
        for hook in hooks:
            hook.stdin.write(self.event())
            hook.stdin.close()
        outputs = [hook.stdout.read().strip() for hook in hooks]
        self.assertEqual([hook.wait(timeout=10) for hook in hooks], [0] * len(hooks))
        self.assertEqual(sorted(name for output in outputs for name in given(output)), ["code", "godot"])
        self.assertEqual(len(self.log()), 2)

    def test_a_compaction_clears_the_session_through_the_hook_command(self):
        groups = [group for group in HOOKS["hooks"]["SessionStart"]
                  if any("/hooks/path_rules.py" in hook["command"] for hook in group["hooks"])]
        self.assertEqual([group["matcher"] for group in groups], ["^compact$"])
        hook = groups[0]["hooks"][0]
        self.assertEqual(hook["command"], self.command()[1]["command"])
        self.assertLessEqual(hook["timeout"], 5)
        self.assertEqual(given(self.run_command(self.event()).stdout.strip()), ["code", "godot"])
        compact = json.dumps({"session_id": "s1", "cwd": str(self.project), "hook_event_name": "SessionStart",
                              "source": "compact"})
        for payload, env in ((compact, {}), ("not json", {}), (compact, {"CLAUDE_PLUGIN_ROOT": "/nonexistent"})):
            with self.subTest(payload=payload, env=env):
                result = self.run_command(payload, **env)
                self.assertEqual((result.returncode, result.stdout), (0, ""))
        self.assertEqual(given(self.run_command(self.event()).stdout.strip()), ["code", "godot"])

    def test_stays_within_budget(self):
        command = "for f in src/a.gd src/b.gd; do cat -n $f; done"
        best = min(self.timed(self.event(tool="Bash", session=f"t{n}", command=command)) for n in range(3))
        self.assertLess(best, BUDGET_S)
        silent = min(self.timed(self.event(tool="Bash", session="t0", command=command)) for _ in range(3))
        self.assertLess(silent, BUDGET_S)

    test_stays_within_budget.LAYER = "performance"  # KIT-077: a latency budget runs alone (performance.yml)

    def timed(self, payload):
        start = time.monotonic()
        result = self.run_command(payload)
        self.assertEqual(result.returncode, 0, result.stderr)
        return time.monotonic() - start


