"""guardrails path-rule hook (KIT-081 stage 3): plugins/guardrails/hooks/path_rules.py gives Claude Code a kit path
rule when a tool call reads or edits a file the rule's globs match, once per session, in a project the kit's sync
generated, and nothing anywhere else.

The unit tests import the script in-process: the glob translation (`**/` may be empty), the path words of a Bash
command, the CLAUDE.md marker gate, the `.ai-kit.yaml` stacks filter through sync-profiles.txt, the once-per-session state, the
log record and a malformed event. The integration tests run the hooks.json command through bash, as Claude Code
does; the performance test holds the hook to its budget, since it runs after every Read and Bash call."""
