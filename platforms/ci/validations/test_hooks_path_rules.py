    def tearDownClass(cls):
        cls.tmp.cleanup()

    def check_with(self, command):
        kit = Path(tempfile.mkdtemp(dir=self.tmp.name)) / "kit"
        shutil.copytree(self.template, kit)
        hooks = json.loads((kit / self.HOOKS_REL).read_text(encoding="utf-8"))
        groups = hooks["hooks"]["PostToolUse"]
        found = [group for group in groups if "/hooks/path_rules.py" in group["hooks"][0]["command"]]
        self.assertEqual(len(found), 1)
        if command is None:
            groups.remove(found[0])
        else:
            found[0]["hooks"][0]["command"] = command
        (kit / self.HOOKS_REL).write_text(json.dumps(hooks, indent=2) + "\n", encoding="utf-8")
        result = subprocess.run([sys.executable, "-B", str(kit / "platforms/ci/validations/check_kit.py")],
                                capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        return result.stdout + result.stderr

    def test_check_kit_fails_a_broken_hook(self):
        always = json.dumps({"hookSpecificOutput": {"hookEventName": "PostToolUse",
                                                    "additionalContext": "ai-kit path rule `godot` (x)"}})
        broken = {
            "gives nothing": ("true # /hooks/path_rules.py",
                              "path-rule hook case 'a Read in a godot project' must give the rules code, godot"),
            "gives it everywhere": (f"echo '{always}' # /hooks/path_rules.py",
                                    "path-rule hook case 'the same session again' must stay silent"),
            "fails": ("exit 1 # /hooks/path_rules.py", "path-rule hook case 'malformed input' must exit 0"),
            "missing": (None, "PostToolUse needs one path-rule hook"),
        }
        for name, (command, message) in broken.items():
            with self.subTest(name=name):
                self.assertIn(message, self.check_with(command))

