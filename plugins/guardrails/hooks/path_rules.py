#!/usr/bin/env python3
"""guardrails path-rule hook (KIT-081 stage 3): gives Claude Code a kit path rule when a tool call reads or edits a
file the rule's `paths` globs match, once per session per rule, as PostToolUse additionalContext.

Claude Code loads a path rule by itself only from a project's .claude/rules/, where sync-project.sh copied the kit
rules until KIT-081 stage 3. The plugin now gives them: hooks.json runs this file after Read, Edit, Write, MultiEdit,
NotebookEdit, Bash and Grep.

- Gate: the project root is $CLAUDE_PROJECT_DIR, else the event's cwd. The hook acts only when the first line of that
  root's CLAUDE.md is the marker sync-project.sh writes; in any other repository it prints nothing, since the plugin
  is enabled for the user everywhere.
- Rules: the project's stacks select the rules through sync-profiles.txt next to this file, as they selected the
  copies: the profile's `stacks` (KIT-087 P2a: `.ai-kit.yaml`, else the marker, through the kit resolver; read by
  hook_profile.py beside this file, cached per session), else, when the resolver is missing or refuses the profile,
  the profiles of the marker's list (`docs,godot:client` gives docs and godot). A rule's globs are the kit's own:
  the :<dir> and sdd.rule_paths folder scopes the copies carried only narrowed them, and the Codex AGENTS.md blocks
  keep them.
- Match: the candidates are tool_input file_path, notebook_path and path, and the path-like words of a Bash command
  (`cat a.gd`, `sed -n '1,20p' ./src/a.gd`, the files of a `for f in ...` loop, `b.gd:12` as grep prints it). Each is
  made relative to the root; one that resolves outside it is also matched as written. A glob supports `**/`, `**`,
  `*` and `?`, the forms the kit rules use.
- Once per session: the rule names given are kept in $CLAUDE_PLUGIN_DATA/path-rules/<session_id>.json under a lock,
  and a session's first file prunes the files older than PRUNE_DAYS. Without CLAUDE_PLUGIN_DATA nothing is given,
  since the promise cannot hold. A rule is recorded only once its text is read, so an error before then loses nothing.
- Compaction: hooks.json also runs this file on SessionStart with matcher `compact`. A compaction summarizes the
  conversation and may drop the rule text given earlier, so that event deletes the session's state file and the next
  matching call gives the rules again; at worst a rule the summary kept is given twice.
- Log: each delivery appends one record, load_reason kit_hook_path_match, to the InstructionsLoaded hook's
  $CLAUDE_PLUGIN_DATA/instructions-loaded.jsonl (same fields, lock and rotation), which skill_usage.py --rules counts.
- Failure: the hook never blocks a tool; any error exits 0 with nothing on stdout.

Python 3.9, standard library only: hooks.json runs the system python3.
"""
import json
import os
import re
import sys
import time
from pathlib import Path

PLUGIN = Path(__file__).resolve().parent.parent
RULES = PLUGIN / "rules"
PROFILE_MAP = PLUGIN / "hooks" / "sync-profiles.txt"
# Line 1 of the CLAUDE.md sync-project.sh generates (KIT-081 stage 2b); the same pattern as its claude_profile.
MARKER = re.compile(r"^<!-- generated by agent-rules-kit sync-project\.sh v[^;]*; profile ([^; ]+);"
                    r" AGENTS\.md is the source -->$")
CONTEXT = "ai-kit path rule"  # how each delivered block starts; check_kit.py looks for it
LOAD_REASON = "kit_hook_path_match"
LOG = "instructions-loaded.jsonl"
LOG_MAX = 5 * 2**20  # the InstructionsLoaded hook's rotation size
STATE = "path-rules"
PRUNE_DAYS = 3
PATH_KEYS = ("file_path", "notebook_path", "path")
MAX_WORDS = 256  # a long Bash command (a heredoc) is cut there; the hook runs on every call
LINE_SUFFIX = re.compile(r":\d+(?::\d+)?$")  # grep -n and compiler output: b.gd:12, b.gd:12:3
UNSAFE = re.compile(r"[^A-Za-z0-9_.-]")


def glob_regex(glob):
    """The anchored regex of a kit glob: `**/` is any number of folders, none included; `**` anything; `*` and `?`
    stay inside one folder."""
    out, index = [], 0
    while index < len(glob):
        if glob.startswith("**/", index):
            out.append("(?:.*/)?")
            index += 3
        elif glob.startswith("**", index):
            out.append(".*")
            index += 2
        elif glob[index] == "*":
            out.append("[^/]*")
            index += 1
        elif glob[index] == "?":
            out.append("[^/]")
            index += 1
        else:
            out.append(re.escape(glob[index]))
            index += 1
    return re.compile("".join(out) + r"\Z")


def read_rule(path):
    """(the `paths` globs, the body after the frontmatter) of a kit rule file."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != "---" or "---" not in lines[1:]:
        return [], ""
    end = lines.index("---", 1)
    globs, inside = [], False
    for line in lines[1:end]:
        if line == "paths:":
            inside = True
        elif inside and line.startswith(" "):
            item = re.match(r"^\s+-\s+(.+)$", line)
            if item:
                globs.append(item.group(1).strip().strip("\"'"))
        else:
            inside = False
    return globs, "\n".join(lines[end + 1:]).strip()


def state_file(data, session):
    """The session's state file under $CLAUDE_PLUGIN_DATA; the session id never leaves the state folder."""
    return Path(data) / STATE / f"{UNSAFE.sub('_', session)[:128] or 'unknown'}.json"


def marker_profiles(root):
    """The profile names the sync marker on line 1 of <root>/CLAUDE.md records, or None when the project is not one
    the kit's sync generated."""
    try:
        with open(os.path.join(root, "CLAUDE.md"), encoding="utf-8") as handle:
            first = handle.readline(1024).rstrip("\r\n")
    except (OSError, ValueError):
        return None
    found = MARKER.match(first)
    if not found:
        return None
    return {entry.split(":", 1)[0] for entry in found.group(1).split(",") if entry}


def profile_stacks(root, env, session):
    """The stack names the project's resolved profile gives (hook_profile.py, KIT-087 P2a), or None when it gives
    none: no resolver, a refused profile, or no stacks."""
    import importlib.util
    sys.dont_write_bytecode = True  # no __pycache__ in the plugin folder
    spec = importlib.util.spec_from_file_location("ai_kit_hook_profile", Path(__file__).resolve().parent /
                                                  "hook_profile.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    found = module.view(root, env, session)
    names = set()
    for value in ((found or {}).get("stacks") or {}).values():
        names.update([value] if isinstance(value, str) else value if isinstance(value, list) else [])
    return names or None


def selected_rules(profiles):
    """The rule names the map gives to any of `profiles`, in map order."""
    names = []
    for line in PROFILE_MAP.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        entry, _, receivers = line.partition("|")
        entry = entry.strip()
        if entry.startswith("rules/") and entry.endswith(".md") and profiles & set(receivers.split()):
            names.append(entry[len("rules/"):-len(".md")])
    return names


def command_words(command):
    """The words of a shell command, quotes removed and operators split off; a command shlex cannot parse (an open
    quote) falls back to whitespace."""
    import shlex
    try:
        lexer = shlex.shlex(command, posix=True, punctuation_chars=True)
        lexer.whitespace_split = True
        words = []
        for word in lexer:
            words.append(word)
            if len(words) >= MAX_WORDS:
                break
        return words
    except ValueError:
        return command.split()[:MAX_WORDS]


def path_words(command):
    """The path-like words of a shell command: an option's value after `=`, a trailing `:line[:column]` or
    punctuation dropped, kept when it holds a `/` or a `.`; variables, URLs and bare dots are not paths."""
    found = []
    for word in command_words(command):
        if word.startswith("-"):
            word = word.partition("=")[2]
        word = LINE_SUFFIX.sub("", word.rstrip(":,;)"))
        if not word or "$" in word or "://" in word or not word.strip("."):
            continue
        if "/" in word or "." in word:
            found.append(word)
    return found


def candidates(event):
    """The raw paths a tool call names."""
    tool_input = event.get("tool_input")
    if not isinstance(tool_input, dict):
        return []
    found = [tool_input[key] for key in PATH_KEYS if isinstance(tool_input.get(key), str) and tool_input[key]]
    command = tool_input.get("command")
    if event.get("tool_name") == "Bash" and isinstance(command, str):
        found += path_words(command)
    return found


def match_forms(raw, root, cwd):
    """(the forms of a candidate the globs are matched against, its absolute path): the path relative to the root,
    and also the word as written when it resolves outside the root."""
    full = os.path.realpath(raw if os.path.isabs(raw) else os.path.join(cwd, raw))
    relative = os.path.relpath(full, root).replace(os.sep, "/")
    forms = [relative]
    if relative == ".." or relative.startswith("../"):
        bare = raw.replace(os.sep, "/")
        while bare.startswith("./"):
            bare = bare[2:]
        forms.append(bare)
    return forms, full


def claim(state, names):
    """The names among `names` this session has not been given yet, now recorded as given; one lock covers the read
    and the write, so parallel tool calls give a rule once. The caller has read every rule of `names` before."""
    try:
        import fcntl
    except ImportError:  # no flock on this platform: a rare double delivery is the cost
        fcntl = None
    with open(state, "a+", encoding="utf-8") as handle:
        if fcntl:
            fcntl.flock(handle, fcntl.LOCK_EX)
        handle.seek(0)
        try:
            recorded = json.loads(handle.read() or "[]")
        except ValueError:
            recorded = []
        given = {name for name in recorded if isinstance(name, str)} if isinstance(recorded, list) else set()
        fresh = [name for name in names if name not in given]
        if fresh:
            handle.seek(0)
            handle.truncate()
            handle.write(json.dumps(sorted(given | set(fresh))))
    return fresh


def prune(folder, keep):
    """Deletes the session files of `folder` older than PRUNE_DAYS, except `keep`."""
    cutoff = time.time() - PRUNE_DAYS * 86400
    with os.scandir(folder) as entries:
        for entry in entries:
            try:
                if entry.name.endswith(".json") and entry.path != str(keep) and entry.stat().st_mtime < cutoff:
                    os.unlink(entry.path)
            except OSError:
                continue


def append_log(data, records):
    """Appends the records to the InstructionsLoaded hook's log under its lock, rotating it past LOG_MAX."""
    try:
        import fcntl
    except ImportError:
        fcntl = None
    log = data / LOG
    with open(str(log) + ".lock", "a") as lock:
        if fcntl:
            fcntl.flock(lock, fcntl.LOCK_EX)
        if log.is_file() and log.stat().st_size > LOG_MAX:
            os.replace(log, str(log) + ".1")
        with open(log, "a", encoding="utf-8") as handle:
            handle.writelines(json.dumps(record, ensure_ascii=False) + "\n" for record in records)


def block(name, globs, trigger, body):
    return (f"{CONTEXT} `{name}` (plugin guardrails, `rules/{name}.md`; paths "
            + ", ".join(f"`{glob}`" for glob in globs)
            + f"): this tool call touched `{trigger}`, so the rule below holds for every file its paths match, for the"
            f" rest of this session. Kit files this rule names: skill `<skill>`, reference `<file>` is"
            f" `{PLUGIN}/skills/<skill>/references/<file>`.\n\n{body}")


def forget(event, env):
    """SessionStart: after a compaction, deletes the session's state file so its rules are given again."""
    data = env.get("CLAUDE_PLUGIN_DATA")
    session = event.get("session_id") if isinstance(event.get("session_id"), str) else ""
    if event.get("source") == "compact" and data:
        try:
            state_file(data, session).unlink()
        except FileNotFoundError:
            pass
    return ""


def run(text, env):
    """The hook's stdout for one PostToolUse event: a JSON document, or "" when no rule is due. A SessionStart event
    only clears the session's state after a compaction."""
    event = json.loads(text)
    if not isinstance(event, dict):
        return ""
    if event.get("hook_event_name") == "SessionStart":
        return forget(event, env)
    cwd = event.get("cwd") if isinstance(event.get("cwd"), str) and event.get("cwd") else os.getcwd()
    root = env.get("CLAUDE_PROJECT_DIR") or cwd
    profiles = marker_profiles(root)
    data = env.get("CLAUDE_PLUGIN_DATA")
    raws = candidates(event) if profiles and data else []
    if not raws:
        return ""
    session = event.get("session_id") if isinstance(event.get("session_id"), str) else ""
    try:
        profiles = profile_stacks(root, env, session) or profiles
    except Exception:  # noqa: BLE001 - the profile only refines the marker's list
        pass
    root = os.path.realpath(root)
    forms = [match_forms(raw, root, cwd) for raw in raws]
    # rule name -> (globs, the trigger as shown: relative, or as written outside the root; its real path; the body):
    # the body comes from this one read, so nothing is read after the claim
    hits = {}
    for name in selected_rules(profiles):
        globs, body = read_rule(RULES / f"{name}.md")
        patterns = [glob_regex(glob) for glob in globs]
        for shown, full in forms:
            if any(pattern.match(form) for pattern in patterns for form in shown):
                hits[name] = (globs, shown[-1], full, body)
                break
    if not hits:
        return ""
    state = state_file(data, session)
    folder = state.parent
    folder.mkdir(parents=True, exist_ok=True)
    if not state.exists():
        try:
            prune(folder, state)
        except OSError:
            pass  # housekeeping only; the rules still reach the session
    fresh = claim(state, list(hits))
    if not fresh:
        return ""
    parts, records = [], []
    for name in fresh:
        globs, shown, full, body = hits[name]
        parts.append(block(name, globs, shown, body))
        records.append({"ts": int(time.time()), "session_id": session or None, "cwd": event.get("cwd"),
                        "file_path": str(RULES / f"{name}.md"), "memory_type": None, "load_reason": LOAD_REASON,
                        "globs": globs, "trigger_file_path": full, "parent_file_path": None})
    try:
        append_log(Path(data), records)
    except OSError:
        pass  # the log serves later measurements; the rule still reaches the session
    return json.dumps({"hookSpecificOutput": {"hookEventName": "PostToolUse",
                                              "additionalContext": "\n\n".join(parts)}}, ensure_ascii=False)


def main():
    try:
        output = run(sys.stdin.read(), os.environ)
        if output:
            sys.stdout.write(output + "\n")
    except Exception:  # noqa: BLE001 - a hook that fails must never block the tool call it follows
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
