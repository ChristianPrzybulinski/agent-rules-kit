#!/usr/bin/env bash
# Scaffold for the eval case: a Spring service with field injection, synced with the kit's java profile: CLAUDE.md
# carries the marker sync-project.sh writes and no rule is copied, so the guardrails plugin's path-rule hook gives the
# `java` rule when the case reads a matching file (KIT-081 stage 3; KIT-080, #275). The hook and the rule are read
# from this case's plugin folder; a scaffold that cannot reach them stops instead of testing nothing.
set -euo pipefail
plugin="$(dirname "${BASH_SOURCE[0]}")/../.."
[[ -f "$plugin/hooks/path_rules.py" && -f "$plugin/rules/java.md" ]] \
  || { echo "fixture: the kit path-rule hook or rules/java.md is not reachable from the scaffold" >&2; exit 1; }
version="$(sed -n 's/^ *"version": *"\([^"]*\)".*/\1/p' "$plugin/plugin.json" | head -n 1)"
git init -q -b main .
printf '<!-- generated by agent-rules-kit sync-project.sh v%s; profile java; AGENTS.md is the source -->\n' \
  "$version" > CLAUDE.md
mkdir -p src/main/java/game
printf '<project><modelVersion>4.0.0</modelVersion><groupId>game</groupId><artifactId>game</artifactId><version>1</version></project>\n' > pom.xml
cat > src/main/java/game/PlayerService.java <<'JAVA'
package game;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;

@Service
public class PlayerService {
    @Autowired
    private PlayerRepository repo;

    public Player find(long id) { return repo.findById(id); }
}
JAVA
