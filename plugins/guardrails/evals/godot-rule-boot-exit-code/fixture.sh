#!/usr/bin/env bash
# Scaffold for the eval case: a Godot 4 project, synced with the kit's godot profile: CLAUDE.md
# carries the marker sync-project.sh writes, .ai-kit.yaml the stacks, and no rule is copied, so the guardrails plugin's path-rule hook gives the
# `godot` rule when the case reads a matching file (KIT-081 stage 3; KIT-080, #275). The hook and the rule are read
# from this case's plugin folder; a scaffold that cannot reach them stops instead of testing nothing.
set -euo pipefail
plugin="$(dirname "${BASH_SOURCE[0]}")/../.."
[[ -f "$plugin/hooks/path_rules.py" && -f "$plugin/rules/godot.md" ]] \
  || { echo "fixture: the kit path-rule hook or rules/godot.md is not reachable from the scaffold" >&2; exit 1; }
version="$(sed -n 's/^ *"version": *"\([^"]*\)".*/\1/p' "$plugin/plugin.json" | head -n 1)"
git init -q -b main .
printf '<!-- generated by agent-rules-kit sync-project.sh v%s; AGENTS.md is the source -->\n' "$version" > CLAUDE.md
printf "stacks:\n  '.': godot\n" > .ai-kit.yaml
printf '; Engine configuration file.\nconfig_version=5\n\n[application]\nconfig/name="Boot"\nrun/main_scene="res://main.tscn"\n' > project.godot
printf 'extends Node\n\nfunc _ready() -> void:\n\tprint("ready")\n' > main.gd
