#!/usr/bin/env bash
# Scaffold for the eval case: a JUnit test whose assertion passes on a zero return, synced with the kit's java profile: CLAUDE.md
# carries the marker sync-project.sh writes and no rule is copied, so the guardrails plugin's path-rule hook gives the
# `tests` rule when the case reads a matching file (KIT-081 stage 3; KIT-080, #275). The hook and the rule are read
# from this case's plugin folder; a scaffold that cannot reach them stops instead of testing nothing.
set -euo pipefail
plugin="$(dirname "${BASH_SOURCE[0]}")/../.."
[[ -f "$plugin/hooks/path_rules.py" && -f "$plugin/rules/tests.md" ]] \
  || { echo "fixture: the kit path-rule hook or rules/tests.md is not reachable from the scaffold" >&2; exit 1; }
version="$(sed -n 's/^ *"version": *"\([^"]*\)".*/\1/p' "$plugin/plugin.json" | head -n 1)"
git init -q -b main .
printf '<!-- generated by agent-rules-kit sync-project.sh v%s; profile java; AGENTS.md is the source -->\n' \
  "$version" > CLAUDE.md
mkdir -p src/test/java/game
cat > src/test/java/game/PriceCalculatorTest.java <<'JAVA'
package game;

import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.List;
import org.junit.jupiter.api.Test;

class PriceCalculatorTest {
    @Test
    void totalIsComputed() {
        var calc = new PriceCalculator(new FixedTaxRate(0.10));
        long total = calc.total(List.of(new Line("sword", 2, 1500)));
        assertTrue(total >= 0);
    }
}
JAVA
