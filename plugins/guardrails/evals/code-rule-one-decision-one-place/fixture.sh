#!/usr/bin/env bash
# Scaffold for the eval case: two GDScript files that copy one threshold, synced with the kit's godot profile: CLAUDE.md
# carries the marker sync-project.sh writes and no rule is copied, so the guardrails plugin's path-rule hook gives the
# `code` rule when the case reads a matching file (KIT-081 stage 3; KIT-080, #275). The hook and the rule are read
# from this case's plugin folder; a scaffold that cannot reach them stops instead of testing nothing.
set -euo pipefail
plugin="$(dirname "${BASH_SOURCE[0]}")/../.."
[[ -f "$plugin/hooks/path_rules.py" && -f "$plugin/rules/code.md" ]] \
  || { echo "fixture: the kit path-rule hook or rules/code.md is not reachable from the scaffold" >&2; exit 1; }
version="$(sed -n 's/^ *"version": *"\([^"]*\)".*/\1/p' "$plugin/plugin.json" | head -n 1)"
git init -q -b main .
printf '<!-- generated by agent-rules-kit sync-project.sh v%s; profile godot; AGENTS.md is the source -->\n' \
  "$version" > CLAUDE.md
mkdir -p features/party app/network
printf 'extends Node\n\nfunc can_show_evolve_button(level: int) -> bool:\n\treturn level >= 30\n' > features/party/party_panel.gd
printf 'extends RefCounted\n\nfunc is_valid_evolve(level: int) -> bool:\n\tif level < 30:\n\t\treturn false\n\treturn true\n' > app/network/evolve_request.gd
